"""Checks that need a container engine: `al gen` adds the engine to the image recipe only when a
podman option asks for it, `al compile` warns about a zero-touch check outside the sandbox, and
`al explain` says where a check runs and what its skip rules are."""
from __future__ import annotations

import importlib.util
from pathlib import Path

from conftest import ROOT, al

SPEC = importlib.util.spec_from_file_location("nested_engine_under_test",
                                              ROOT / "kit" / "runtime" / "adw_modules" / "nested_engine.py")
nested_engine = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(nested_engine)

LAYER = """#lang al
(agentic-layer #:name "notes" #:description "Agentic layer of a tiny test app"
  (codebase #:root "../notes" #:languages (python)
    (cmd test "./test.sh" #:timeout 60)
    (cmd engine-test "sh engine-test.sh" #:timeout 600))
  (layer sibling)
  (environment worktree)
  (environment nix-devshell #:packages ("python312"))
  (environment podman #:id box #:packages ("git") #:setup ("echo hi") {box})
  (environment podman #:id engine #:packages ("git") #:nested-engine #t #:agent-inside #f)
  (command plan #:template plan-chore #:output path)
  (command review #:template review #:output json)
  (review auto #:id zero-touch #:ship merge #:require-checks (test))
  (adw zte #:description "Ships without a person" #:environment (worktree box) #:review zero-touch
    (steps (run plan #:command plan #:args ("$prompt"))
           (check test #:cmd test #:forbid-skip-reason "no podman" #:max-skipped 0)
           (check engine-test #:cmd engine-test #:in {check_in})
           (review) (ship))))
"""

BEFORE = """# Generated by al from agentic.rkt — do not edit.
FROM docker.io/library/debian:stable-slim
RUN apt-get update && apt-get install -y --no-install-recommends git && rm -rf /var/lib/apt/lists/*
RUN echo hi
ENV HOME=/tmp/home
RUN mkdir -p /tmp/home && chmod 1777 /tmp/home
WORKDIR /work
"""


def _layer(app: Path, *, box: str = "", check_in: str = "engine") -> Path:
    layer = app.parent / "notes.al"
    layer.mkdir(exist_ok=True)
    (layer / "agentic.rkt").write_text(LAYER.format(box=box, check_in=check_in))
    return layer


def test_gen_adds_the_engine_to_the_image_only_when_asked(app) -> None:
    layer = _layer(app, box="#:nested-engine #t")
    al("gen", layer)
    containerfile = (layer / "env" / "Containerfile").read_text()
    assert ("RUN apt-get update && apt-get install -y --no-install-recommends git podman fuse-overlayfs "
            "&& rm -rf /var/lib/apt/lists/*") in containerfile.splitlines()
    lines = containerfile.splitlines()
    assert "COPY al-engine/ /etc/containers/" in lines
    assert lines.index("COPY al-engine/ /etc/containers/") < lines.index("ENV HOME=/tmp/home")
    assert (layer / "env" / "al-engine" / "containers.conf").read_text() == nested_engine.CONTAINERS_CONF
    assert (layer / "env" / "al-engine" / "storage.conf").read_text() == nested_engine.STORAGE_CONF

    plain = app.parent / "plain.al"
    plain.mkdir()
    source = LAYER.format(box="", check_in="box").replace(" #:nested-engine #t", "")
    (plain / "agentic.rkt").write_text(source)
    al("gen", plain)
    assert (plain / "env" / "Containerfile").read_text() == BEFORE
    assert not (plain / "env" / "al-engine").exists()


def test_compile_warns_for_a_zero_touch_check_outside_the_sandbox(app) -> None:
    cp = al("compile", _layer(app, check_in="nix-devshell"))
    assert cp.returncode == 0
    assert ("al: warning: workflow zte ships without a person, but check engine-test runs #:in nix-devshell "
            "(a nix-devshell environment), outside its podman sandbox") in cp.stderr.splitlines(), cp.stderr
    cp = al("compile", _layer(app, check_in="engine"))
    assert "outside its podman sandbox" not in cp.stderr, cp.stderr   # #:in a podman option stays sandboxed


def test_explain_says_where_a_check_runs_and_its_skip_rules(app, tmp_path) -> None:
    layer = _layer(app)
    out = tmp_path / "explained.md"
    al("explain", layer, "--md", out)
    text = out.read_text()
    assert "check `engine-test`: run the `engine-test` command in `engine`" in text
    assert ("check `test`: run the `test` command; fails when more than 0 tests are skipped; "
            "fails when a test is skipped because of \"no podman\"") in text
    assert "with a container engine of its own (nested, isolated from the host's)" in text
    assert text.count("with a container engine of its own") == 1   # only the option that asks for it
