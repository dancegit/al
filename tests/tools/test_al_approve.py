"""`al run --approve WHAT`, `al approve LAYER RUN WHAT…`, `al approve LAYER RUN --all` and
`al approve LAYER RUN ship`: a decision only a person may take, given before a run or after it stopped
for one, on a layer generated by `al gen` (mock agent, --dry-run).
Run with -s to see the commands' output (docs/GUIDE.md quotes it)."""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

from conftest import KIT, al

sys.path.insert(0, str(KIT / "dashboard" / "tests"))
import ship_fixtures as shf  # noqa: E402 — a handed-over run whose gate only asked for a person's yes

STARTED = re.compile(r"^run ([0-9a-f]{8}) started", re.MULTILINE)
PLAN = """# Chore: use the new word

## How it is proven

### Proof plan
| # | Criterion | Proven by | Writes | Needs |
|---|---|---|---|---|
| C1 | the tests pass | `test` | - | approval:vocabulary |
"""


def show(cp) -> str:
    print(f"$ al {' '.join(str(a) for a in cp.args[1:])}\n{cp.stdout}{cp.stderr}", end="")
    return cp.stdout


def _env() -> dict[str, str]:
    return {k: v for k, v in os.environ.items() if k not in ("AL_DECIDER", "AL_APPROVED_BY", "AL_APP_ROOT")}


def _plan_needs_a_person(layer: Path) -> None:
    (layer / "mock").mkdir(exist_ok=True)
    (layer / "mock" / "plan.json").write_text(json.dumps({"layer_files": {"specs/plan-word.md": PLAN},
                                                          "output": "specs/plan-word.md"}))
    (layer / "mock" / "build.json").write_text(json.dumps({"files": {"notes.txt": "a note\n"}, "output": "built"}))


def _state(layer: Path, run: str) -> dict:
    return json.loads((layer / "agents" / run / "state.json").read_text())


def _finished(layer: Path, run: str, timeout: float = 300) -> dict:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            state = _state(layer, run)
            if state.get("status") in ("passed", "failed", "handed-over") and state.get("ended"):
                return state
        except (OSError, ValueError):
            pass
        time.sleep(0.3)
    raise AssertionError(f"run {run} did not finish")


def test_al_run_passes_approve_to_the_run(sibling):
    _plan_needs_a_person(sibling)
    cp = al("run", sibling, "/change", "use", "the", "new", "word", "--dry-run", "--approve", "vocabulary",
            "--who", "ana", env=_env())
    show(cp)
    run = STARTED.search(cp.stdout).group(1)
    state = _state(sibling, run)
    assert state["status"] in ("passed", "handed-over"), cp.stdout
    (given,) = state["approvals"]
    assert (given["what"], given["who"], given["via"]) == ("vocabulary", "ana", "start")
    assert next(r for r in state["steps"] if r["name"] == "prove")["status"] == "passed"


def test_al_approve_resumes_the_run(sibling):
    _plan_needs_a_person(sibling)
    cp = al("run", sibling, "/change", "use", "the", "new", "word", "--dry-run", ok=False, env=_env())
    assert cp.returncode == 1, cp.stdout + cp.stderr
    run = STARTED.search(cp.stdout).group(1)
    assert "proof:     stopped at prove: needs-person (approver)" in cp.stdout
    assert f"proof:needs-person: 1 criterion(s) cannot be proven here; party: approver" in cp.stdout
    assert "build" not in [call["step"] for call in _state(sibling, run)["agent_calls"]]
    out = show(al("approve", sibling, run, "vocabulary", "--who", "ana", env=_env()))
    assert out.strip() == f"approve: approved vocabulary for run {run}; resuming from step prove"
    state = _state(sibling, run)
    deadline = time.monotonic() + 300
    while time.monotonic() < deadline and not (state.get("ended") and state.get("status") != "failed"):
        time.sleep(0.5)
        state = _state(sibling, run)
    assert state["status"] in ("passed", "handed-over"), (sibling / "agents" / run / "resume.log").read_text()
    assert [(a["what"], a["who"], a["via"]) for a in state["approvals"]] == [("vocabulary", "ana", "cli")]
    assert "build" in [call["step"] for call in state["agent_calls"]]


def test_al_approve_refuses_a_running_run(sibling):
    run = "a1b2c3d4"
    directory = sibling / "agents" / run
    directory.mkdir(parents=True)
    (directory / "state.json").write_text(json.dumps({"adw_id": run, "adw": "change", "status": "running"}))
    cp = al("approve", sibling, run, "vocabulary", ok=False, env=_env())
    show(cp)
    assert cp.returncode == 1
    assert cp.stderr.startswith(f"al approve: refused (not-stopped-for-an-approver): run {run} is running")
    assert "approvals" not in _state(sibling, run)
    unknown = al("approve", sibling, "0badc0de", "vocabulary", ok=False, env=_env())
    assert unknown.returncode == 1 and "unknown-run" in unknown.stderr


def test_bad_token_is_exit_2(sibling):
    cp = al("approve", sibling, "a1b2c3d4", "Not A Token", ok=False, env=_env())
    show(cp)
    assert cp.returncode == 2 and "an approval is a word of lower-case letters" in cp.stderr
    assert al("approve", sibling, "a1b2c3d4", ok=False).returncode == 2   # WHAT is required
    run = al("run", sibling, "/change", "x", "--dry-run", "--approve", "Bad Word", ok=False, env=_env())
    assert run.returncode == 2 and "approve: bad approval 'Bad Word'" in run.stderr
    assert not STARTED.search(run.stdout)


def test_al_approve_all_resumes_the_run(sibling):
    _plan_needs_a_person(sibling)
    cp = al("run", sibling, "/change", "use", "the", "new", "word", "--dry-run", ok=False, env=_env())
    assert cp.returncode == 1, cp.stdout + cp.stderr
    run = STARTED.search(cp.stdout).group(1)
    out = show(al("approve", sibling, run, "--all", "--who", "ana", "--note", "agreed in review", env=_env()))
    assert out.splitlines() == [
        f"approve: run {run} waits for your approval of 1 item(s):",
        "approve:   vocabulary: needed by C1: the tests pass",
        "approve: after:     resume from prove",
        f"approve: approved vocabulary for run {run}; resuming from step prove"]
    state = _state(sibling, run)
    deadline = time.monotonic() + 300          # the stopped run is `failed` until its resume ends
    while time.monotonic() < deadline and not (state.get("ended") and state.get("status") != "failed"):
        time.sleep(0.5)
        state = _state(sibling, run)
    assert state["status"] in ("passed", "handed-over"), (sibling / "agents" / run / "resume.log").read_text()
    (given,) = state["approvals"]
    assert (given["what"], given["who"], given["via"], given["note"]) == ("vocabulary", "ana", "cli",
                                                                         "agreed in review")
    assert "build" in [call["step"] for call in state["agent_calls"]]


