def test_al_approve_needs_what_or_all(sibling):
    run = "a1b2c3d4"
    neither = al("approve", sibling, run, ok=False, env=_env())
    both = al("approve", sibling, run, "vocabulary", "--all", ok=False, env=_env())
    for cp in (neither, both):
        assert cp.returncode == 2 and "al approve: name what you approve (WHAT …) or --all" in cp.stderr
    note = al("approve", sibling, run, "vocabulary", "--note", "agreed", ok=False, env=_env())
    assert note.returncode == 2 and "al approve: --note goes with --all or ship" in note.stderr
    assert not (sibling / "agents" / run).exists()


# ---------------------------------------------------------------- al approve LAYER RUN ship

SHIP_RUN = "f4000001"


def _rev(repo: Path, ref: str) -> str:
    return subprocess.run(["git", "-C", str(repo), "rev-parse", ref], capture_output=True, text=True, check=True,
                          timeout=60).stdout.strip()


def _ship_stop(layer: Path, **how) -> tuple[Path, dict]:
    """A handed-over run of the layer's workflow whose gate said diff-too-large, with a stage branch
    (kit/dashboard/tests/ship_fixtures.py; the check names are the layer's own)."""
    app = layer.parent / "notes"
    return app, shf.add_ship_run(layer, app, SHIP_RUN, **how)


def test_al_approve_ship_merges_into_the_stage(sibling):
    app, state = _ship_stop(sibling)
    commit, default = state["ship"]["commit"], _rev(app, "main")
    cp = al("approve", sibling, SHIP_RUN, "ship", "--who", "ana", "--note", "agreed", env=_env())
    out = show(cp)
    assert out.splitlines() == [
        f"approve: run {SHIP_RUN} waits for your approval of 1 item(s):",
        f"approve:   {shf.DIFF}: 3148 lines in 1 file(s) → integration; checks: 1 passed",
        "approve:   target:    integration",
        "approve:   diff:      3148 lines, 1 file(s)",
        f"approve:     shelf_{SHIP_RUN}.py",
        "approve:   checks:    test passed",
        "approve: after:     the run's branch is merged into integration (fast-forward)",
        f"approve: approved by ana: {state['branch']} is merged into integration ({commit[:7]})"]
    assert _rev(app, "integration") == commit and _rev(app, "main") == default
    (given,) = _state(sibling, SHIP_RUN)["approvals"]
    assert (given["what"], given["who"], given["via"], given["note"]) == (f"ship:{shf.DIFF}", "ana", "cli", "agreed")
    settled = json.loads((sibling / "agents" / SHIP_RUN / "settlement.json").read_text())
    assert (settled["as"], settled["by"], settled["who"], settled["via"]) == ("landed", commit, "ana", "cli")
    again = al("approve", sibling, SHIP_RUN, "ship", "--who", "ana", ok=False, env=_env())
    assert again.returncode == 1 and "al approve: refused (not-waiting): " in again.stderr


def test_al_approve_ship_refuses_red_checks(sibling):
    app, state = _ship_stop(sibling, checks_exit=1)
    before = _rev(app, "integration")
    cp = al("approve", sibling, SHIP_RUN, "ship", "--who", "ana", ok=False, env=_env())
    show(cp)
    assert cp.returncode == 1
    assert cp.stdout.strip() == (f"approve: run {SHIP_RUN} does not wait for an approval: checks are not all green: "
                                 "test failed")
    assert cp.stderr.startswith("al approve: refused (checks-not-green): checks are not all green: test failed")
    assert "approvals" not in _state(sibling, SHIP_RUN) and _rev(app, "integration") == before
    assert not (sibling / "agents" / SHIP_RUN / "settlement.json").exists()
    note = al("approve", sibling, SHIP_RUN, "vocabulary", "--note", "agreed", ok=False, env=_env())
    assert note.returncode == 2 and "al approve: --note goes with --all or ship" in note.stderr


def test_al_approve_all_takes_a_ship_approval(sibling):
    app, state = _ship_stop(sibling)
    cp = al("approve", sibling, SHIP_RUN, "--all", "--who", "ana", env=_env())
    out = show(cp)
    assert out.splitlines()[-1] == (f"approve: approved by ana: {state['branch']} is merged into integration "
                                    f"({state['ship']['commit'][:7]})")
    assert _rev(app, "integration") == state["ship"]["commit"]
    assert _state(sibling, SHIP_RUN)["approvals"][0]["what"] == f"ship:{shf.DIFF}"
