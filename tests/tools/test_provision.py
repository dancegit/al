# --- provision.sh on fake hosts -------------------------------------------------------------------

def bare_host(tmp_path: Path, family: str) -> Host:
    """A host of `family` missing podman (and its helpers), uv, claude, subids and lingering."""
    host = make_host(tmp_path)
    host.family(family)
    host.remove("uv")
    host.remove("claude")
    (host.root / ".subids-missing").write_text("")
    host.serve_downloads(DOWNLOADS)
    return host


def run_script(layer: Path, host: Host, *args: str, ident: str = "server") -> subprocess.CompletedProcess:
    script = layer / "env/hosts" / ident / "provision.sh"
    return subprocess.run([shutil.which("sh") or "/bin/sh", str(script), *args], cwd=host.root, capture_output=True, text=True,
                          stdin=subprocess.DEVNULL, env={"HOME": str(host.root), "PATH": host.path, "LANG": "C"}, timeout=120)


def installs(host: Host, family: str) -> list[str]:
    return [line for line in host.log(INSTALL[family]) if not line.startswith("-Q")]


@pytest.mark.parametrize("family", ["debian", "fedora", "arch"])
def test_script_check_reports_and_changes_nothing(provisionable, tmp_path, family):
    host = bare_host(tmp_path, family)
    before = host.snapshot()
    cp = run_script(provisionable, host, "--check")
    assert cp.returncode == 0, cp.stdout + cp.stderr
    out = cp.stdout
    assert f"packages ({family}): missing {' '.join(PACKAGES[family])}" in out
    assert f"subids: missing for {HOST_USER}" in out and "uv 9.9.1: missing" in out and "claude 9.9.2: missing" in out
    assert "linger: off" in out
    privileged = [line.strip() for line in out.splitlines() if line.strip().startswith("privileged: ")]
    assert privileged == [f"privileged: sudo -n {al_provision.FAMILIES[family]['install']} {' '.join(PACKAGES[family])}",
                          f"privileged: sudo -n usermod --add-subuids 100000-165535 --add-subgids 100000-165535 {HOST_USER}",
                          f"privileged: sudo -n loginctl enable-linger {HOST_USER}"]
    assert "nothing was changed (--check)" in out
    assert host.snapshot() == before and host.log("sudo") == [] and installs(host, family) == [] and host.log("curl") == []


@pytest.mark.parametrize("family", ["debian", "fedora", "arch"])
def test_script_installs_what_is_missing_then_changes_nothing(provisionable, tmp_path, family):
    host = bare_host(tmp_path, family)
    cp = run_script(provisionable, host, "--yes")
    assert cp.returncode == 0, cp.stdout + cp.stderr
    pkgs = (host.root / ".pkgs").read_text().split()
    assert all(p in pkgs for p in PACKAGES[family])
    assert host.log("sudo") == [f"-n {al_provision.FAMILIES[family]['install']} {' '.join(PACKAGES[family])}",
                                f"-n usermod --add-subuids 100000-165535 --add-subgids 100000-165535 {HOST_USER}",
                                f"-n loginctl enable-linger {HOST_USER}"]
    for name, version in (("uv", "9.9.1"), ("claude", "9.9.2")):
        binary = host.root / ".local/bin" / name
        assert binary.is_file() and os.access(binary, os.X_OK)
        assert version in subprocess.run([str(binary), "--version"], capture_output=True, text=True).stdout
    assert (host.bin / "podman").is_file() and (host.root / ".linger").exists() and not (host.root / ".subids-missing").exists()
    assert "checksum mismatch" not in cp.stdout + cp.stderr and "provisioning: done" in cp.stdout
    calls = (len(host.log("sudo")), len(installs(host, family)), len(host.log("curl")))
    before = host.snapshot()
    again = run_script(provisionable, host, "--yes")
    assert again.returncode == 0 and "provisioning: nothing to do" in again.stdout, again.stdout + again.stderr
    assert (len(host.log("sudo")), len(installs(host, family)), len(host.log("curl"))) == calls
    assert host.snapshot() == before


def test_script_shows_every_privileged_command_before_it_runs(provisionable, tmp_path):
    host = bare_host(tmp_path, "debian")
    cp = run_script(provisionable, host, "--yes")
    lines = cp.stdout.splitlines()
    ran = [(i, line[len("+ sudo "):]) for i, line in enumerate(lines) if line.startswith("+ sudo ")]
    assert len(ran) == 3
    for i, command in ran:
        shown = [j for j, line in enumerate(lines) if line.strip() == f"privileged: sudo {command}"]
        assert shown and shown[0] < i, command
    assert host.log("sudo") == [command for _, command in ran]


def test_script_stops_when_privilege_is_refused(provisionable, tmp_path):
    host = bare_host(tmp_path, "debian")
    (host.root / ".sudo-denied").write_text("")
    before = (host.root / ".pkgs").read_text()
    cp = run_script(provisionable, host, "--yes")
    assert cp.returncode == 3, cp.stdout + cp.stderr
    assert "run these as a privileged user on this machine" in cp.stdout
    for command in (f"sudo apt-get install -y --no-install-recommends {' '.join(PACKAGES['debian'])}",
                    f"sudo usermod --add-subuids 100000-165535 --add-subgids 100000-165535 {HOST_USER}",
                    f"sudo loginctl enable-linger {HOST_USER}"):
        assert f"  {command}" in cp.stdout.splitlines(), command
    assert (host.root / ".pkgs").read_text() == before and host.log("apt-get") == []


def test_script_refuses_a_bad_checksum(provisionable, tmp_path):
    host = bare_host(tmp_path, "debian")
    (host.root / ".curl-tamper").write_text("")
    cp = run_script(provisionable, host, "--yes")
    assert cp.returncode != 0
    assert "checksum mismatch for uv 9.9.1" in cp.stderr
    local_bin = host.root / ".local/bin"
    assert not local_bin.exists() or list(local_bin.iterdir()) == []


SH_BUILTINS = {"echo", "command", "set", "if", "then", "else", "elif", "fi", "for", "do", "done", "while", "read", "printf",
               "exit", "return", "case", "esac", "in", "shift", "trap", "true", "false", "test", ":", "["}


def script_command_words(script: str) -> set[str]:
    """The word that starts each simple command of a script; case patterns, quoted text, function
    names being defined and assignments aside."""
    text = re.sub(r"'[^'\n]*'", "Q", script)
    text = re.sub(r"(?m)^\s*#.*$", "", text)
    text = re.sub(r"\$\(\([^)]*\)\)", "N", text)                               # $((arithmetic))
    text = re.sub(r"(?m)(^|;;|\bin)\s*[^\s()]+(\|[^\s()]+)*\)", r"\1", text)   # case labels: `x86_64) …`, `-h|--help) …`
    text = re.sub(r'"[^"\n]*"', lambda m: re.sub(r"[^$()]", "", m.group(0)) or "S", text)
    words = set()
    for segment in re.split(r"[\n;|&(){}`]+", text):
        tokens = segment.split()
        while tokens and (tokens[0] in ("if", "then", "else", "elif", "do", "while", "!", "in", "$") or re.fullmatch(r"\w+=.*", tokens[0])):
            tokens.pop(0)
        if not tokens or tokens[0] in ("for", "case"):
            continue
        if re.fullmatch(r"[A-Za-z_][\w.-]*", tokens[0]):
            words.add(tokens[0])
    return words


def test_script_uses_only_declared_tools(provisionable):
    script = (provisionable / "env/hosts/server/provision.sh").read_text()
    functions = set(re.findall(r"(?m)^\s*([a-z_]+)\(\) \{", script))
    families = {c for f in al_provision.FAMILIES.values() for c in f["commands"]}
    allowed = SH_BUILTINS | set(al_provision.SCRIPT_TOOLS) | families | functions
    used = script_command_words(script)
    assert used <= allowed, sorted(used - allowed)
    assert {"curl", "sha256sum", "tar", "sudo", "getsubids", "priv"} <= used
