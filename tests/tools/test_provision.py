def test_one_host_declaration_generates_three_committed_files(golden_layer):
    app = golden_layer.parent
    local = json.loads((golden_layer / ".al-manifest.local.json").read_text()) \
        if (golden_layer / ".al-manifest.local.json").is_file() else {}
    tracked = git(app, "ls-files").splitlines()
    for host in ("server", "nix"):
        for name in FILES:
            rel = f"env/hosts/{host}/{name}"
            assert (golden_layer / rel).is_file(), rel
            assert rel not in local, f"{rel} is recorded as machine-local"
            assert f"agentic/{rel}" in tracked, f"{rel} is not committed"
        assert os.access(golden_layer / f"env/hosts/{host}/provision.sh", os.X_OK)
        assert not os.access(golden_layer / f"env/hosts/{host}/nixos.nix", os.X_OK)
    assert al("check", golden_layer).returncode == 0


def test_provision_outputs_equal_the_golden_files(golden_layer):
    update = os.environ.get("AL_UPDATE_PROVISION_GOLDEN") == "1"
    for name in FILES:
        produced = (golden_layer / "env/hosts/server" / name).read_text()
        if update:
            (GOLDEN / name).write_text(produced)
        assert produced == (GOLDEN / name).read_text(), (
            f"env/hosts/server/{name} differs from tests/tools/golden/provision/{name}; if the change is intended, "
            "rerun with AL_UPDATE_PROVISION_GOLDEN=1, which rewrites the golden files")


def test_provision_outputs_name_no_host_user_path_or_secret(golden_layer, tmp_path):
    pins = json.loads(GOLDEN_PINS.read_text())
    urls = {a["url"] for p in pins.values() for a in p["assets"].values()}
    forbidden = [str(tmp_path), "deploy-host.example", HOST_USER, str(Path.home())]
    if os.environ.get("USER"):
        forbidden.append(f"/home/{os.environ['USER']}")
    for host in ("server", "nix"):
        for name in FILES:
            text = (golden_layer / "env/hosts" / host / name).read_text()
            for word in forbidden:
                assert word not in text, f"{host}/{name} names {word}"
            assert "@" not in text, f"{host}/{name} holds an @"
            stripped = text
            for url in urls:
                stripped = stripped.replace(url, "")
            assert "://" not in stripped, f"{host}/{name} holds a URL that is not a pinned download"


