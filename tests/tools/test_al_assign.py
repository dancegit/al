@pytest.fixture()
def scenario(tmp_path: Path, scenario_root: Path) -> dict[str, Path]:
    root = tmp_path / "s"
    shutil.copytree(scenario_root, root, symlinks=True)
    return {"root": root, "repo": root / "pantry", "layer": root / "pantry.al"}


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True).stdout.strip()


def assign(scenario, *args: str, ok: bool = False) -> subprocess.CompletedProcess:
    return al("assign", scenario["layer"], *args, ok=ok)


def _tool():
    """tools/al loaded as a module (it has no .py suffix), for its constants."""
    loader = importlib.machinery.SourceFileLoader("al_tool_for_assign", str(AL))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    module = importlib.util.module_from_spec(spec)
    sys.modules[loader.name] = module
    loader.exec_module(module)
    return module


def test_gen_writes_assign_script_and_check_needs_it(sibling) -> None:
    script = sibling / "adws" / "assign.py"
    assert script.is_file() and os.access(script, os.X_OK)
    text = script.read_text()
    assert text.startswith("#!/usr/bin/env -S uv run --quiet --script\n")
    assert "assign.main(Path(__file__).resolve().parent.parent, sys.argv[1:])" in text
    assert (sibling / "adws" / "adw_modules" / "assign.py").is_file()
    assert "adws/assign.py" in manifest(sibling)["files"]
    assert "ok" in al("check", sibling).stdout.lower()
    script.unlink()
    cp = al("check", sibling, ok=False)
    assert cp.returncode != 0 and "missing adws/assign.py" in cp.stdout + cp.stderr
    al("gen", sibling)
    al("check", sibling)
    assert script.read_text() == text, "al gen writes it again, the same"
    tool = _tool()
    assert start_layer.ASSIGN_SCRIPT == tool.ASSIGN_SCRIPT, "the dashboard's test layers use the generator's text"
    assert tool.ASSIGN_SCRIPT.startswith('"""Give a stopped run to an agent')
    assert "Generated by `al gen` for every layer — see adw_modules/assign.py" in tool.ASSIGN_SCRIPT
    # the generated script answers for a layer without runs
    cp = al("assign", sibling, "0badc0de", "--preview", ok=False)
    assert cp.returncode == 3 and cp.stderr.startswith("al assign: unknown-run: ")


def test_preview_prints_the_plan(scenario):
    before = fx.git(scenario["repo"], "for-each-ref")
    cp = assign(scenario, af.REJECTED, "--preview", ok=True)
    lines = cp.stdout.splitlines()
    assert lines[0] == f"run:        {af.REJECTED} (Take a discount off the total)"
    assert lines[1] == "stopped:    handed-over at review: the review rejected it: the change is not right yet"
    assert lines[2] == "plan:       address 1 blocker (the review's patch round) and review once more"
    assert lines[3:9] == [
        f"  1. apply branch {af.branch_of(af.REJECTED)} onto main in a fresh worktree",
        "  2. address the blockers with the review's patch round:",
        "     - total() accepts a negative discount",
        "  3. run the checks again",
        "  4. review once, with no further patch round",
        "  5. ship through the unchanged gate, or back to you with the history"]
    assert lines[-1] == "limit:      0 of 2 used"
    assert str(scenario["root"]) not in cp.stdout
    as_json = json.loads(assign(scenario, af.REJECTED, "--preview", "--json", ok=True).stdout)
    assert (as_json["kind"], as_json["blocked"], as_json["moved"]) == ("blockers", "", False)
    # every stopped run has a plan of the expected kind, and a preview starts and writes nothing
    for run, kind in af.KINDS.items():
        found = json.loads(assign(scenario, run, "--preview", "--json", ok=True).stdout)
        assert found["kind"] == kind, (run, found["kind"], found["blocked_why"])
    assert fx.integration_runs(scenario["layer"]) == [] and fx.git(scenario["repo"], "for-each-ref") == before
    assert not list((scenario["layer"] / "agents").glob("*/assign.json"))
    by_branch = assign(scenario, af.branch_of(af.REJECTED), "--preview", ok=True)
    assert by_branch.stdout == cp.stdout, "a branch names its run"
    listed = assign(scenario, "--all", "--preview", ok=True).stdout.splitlines()
    assert listed[0].startswith(f"{af.FAILED_CHECK}  check") and listed[1].startswith(f"{af.NOTHING}  start-again")
    assert any(line.startswith(f"{af.PERSON}  person       skipped: needs-a-person: ") for line in listed)
    assert sorted(line.split()[0] for line in listed) == sorted(af.KINDS), "exactly the runs under Needs you"
    assert [line.split()[1] for line in listed if "skipped" not in line] == [
        "check", "start-again", "integrate", "integrate", "blockers", "blockers"]


