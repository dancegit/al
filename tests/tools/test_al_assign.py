def test_al_runs_names_al_assign_for_every_run_that_needs_you(scenario):
    out = al("runs", scenario["layer"]).stdout
    nexts = [line for line in out.splitlines() if line.lstrip().startswith("→ ")]
    assert nexts and all(" or: al assign " in line for line in nexts), out
    assert f"; or: al assign {scenario['layer']} {af.REJECTED}" in out
    assert "Give to an agent" not in out, "the dashboard's words are not a command"
