@pytest.mark.parametrize("transport", ["clone", "push"])
def test_update_fast_forwards_an_existing_deployment(deployable, tmp_path, transport):
    app, host = deployable.parent, prepared(tmp_path)
    if transport == "clone":
        with_origin(app, tmp_path)
    deploy(deployable, host)
    checkout = host.root / "al/notes"
    first = git(checkout, "rev-parse", "HEAD")
    state = checkout / "agentic/agents/abcd1234/state.json"
    state.parent.mkdir(parents=True)
    state.write_text('{"adw_id": "abcd1234", "status": "running"}')
    (app / "app.py").write_text("NOTES = ['more']\n")
    commit(app, "more notes")
    new = git(app, "rev-parse", "main")
