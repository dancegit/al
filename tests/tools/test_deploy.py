def prepared(tmp_path: Path) -> Host:
    """A host that can run the notes layer: agent login and both secrets in place."""
    host = make_host(tmp_path)
    host.login("claude-code")
    host.set_env_file("notes", FORGEJO_TOKEN="x", ADW_WEBHOOK_SECRET="y")
    return host


def deploy(layer: Path, host: Host, *args, ok: bool = True, label: str = LABEL, env: dict | None = None):
    return al("deploy", layer, "--to", label, *args, env={**host.env(), **(env or {})}, ok=ok)


def changes(host: Host) -> list[str]:
    return [line for line in host.log("systemctl") if re.search(r"\b(enable|restart|daemon-reload)\b", line)]


def with_origin(app: Path, tmp_path: Path) -> Path:
    bare = tmp_path / "remote" / "notes.git"
    bare.parent.mkdir()
    git(bare.parent, "init", "-q", "--bare", "-b", "main", "notes.git")
    git(app, "remote", "add", "origin", str(bare))
    git(app, "push", "-q", "origin", "main")
    return bare


