SHELL_WORDS = {"echo", "command", "set", "if", "then", "else", "elif", "fi", "for", "do", "done", "while", "read", "printf", "exit", ":"}


def command_words(script: str) -> set[str]:
    """The word that starts each pipeline segment of a script (quoted text and assignments aside)."""
    text = re.sub(r"'[^']*'", "Q", script)
    words = set()
    for segment in re.split(r"[\n;|&(){}`]+", text):
        tokens = segment.replace('"', " ").split()
        while tokens and (tokens[0] in ("if", "then", "else", "elif", "do", "while", "!") or re.fullmatch(r"\w+=.*", tokens[0])):
            tokens.pop(0)
        if tokens and tokens[0] == "for":
            continue
        if tokens and re.fullmatch(r"[A-Za-z_:][\w.-]*", tokens[0]):
            words.add(tokens[0])
    return words


