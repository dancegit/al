def add_podman(layer: Path) -> None:
    text = (layer / "agentic.rkt").read_text()
    (layer / "agentic.rkt").write_text(text.replace("  (prompt-input tasklist)\n", "  (prompt-input tasklist)\n  (environment worktree)\n  (environment podman)\n"))
    al("gen", layer)
    commit(layer.parent, "a podman environment", "agentic")


MISSES = {
    "uv": (lambda host, layer: host.remove("uv"), "uv",
           "install uv on the host: https://docs.astral.sh/uv/ (it must be on the login PATH)"),
    "podman-absent": (lambda host, layer: (add_podman(layer), host.remove("podman")), "podman",
                      "install podman and make rootless work: podman info must say rootless: true (subuid/subgid for the user)"),
    "podman-rootful": (lambda host, layer: (add_podman(layer), (host.root / ".rootless").write_text("false\n")), "podman",
                       "install podman and make rootless work: podman info must say rootless: true (subuid/subgid for the user)"),
    "agent-cli": (lambda host, layer: host.remove("claude"), "agent CLI claude",
                  "install the claude CLI on the host and put it on the login PATH"),
    "agent-login": (lambda host, layer: (host.root / ".claude/.credentials.json").unlink(), "agent login claude",
                    "log in on the host (run claude once there) or put ANTHROPIC_API_KEY=… in ~/.config/al/notes.env on the host (chmod 600)"),
    "disk": (lambda host, layer: host.stub("df", 'echo "Filesystem 1024-blocks Used Available Capacity Mounted on"\necho "/dev/x 9999999 1 1048576 1% /"\n'),
             "disk", "free space under the home directory on the host: 1.0 GB free, 5 GB needed"),
    "systemd": (lambda host, layer: host.stub("systemctl", "exit 1\n"), "systemd user session",
                "systemctl --user must work for this user over ssh (pam_systemd; XDG_RUNTIME_DIR set)"),
}


@pytest.mark.parametrize("case", sorted(MISSES))
def test_preflight_reports_each_miss_with_its_fix(deployable, tmp_path, case):
    host = prepared(tmp_path)
    if case == "systemd":       # without a user session the environment cannot be read either: the key stands in for the file
        host.set_env_file("notes", FORGEJO_TOKEN="x", ADW_WEBHOOK_SECRET="y")
    arrange, check, fix = MISSES[case]
    arrange(host, deployable)
    before = host.snapshot()
    cp = deploy(deployable, host, ok=False)
    assert cp.returncode == 1, cp.stdout + cp.stderr
    row = next(line for line in cp.stdout.splitlines() if line.strip().startswith(check + " "))
    assert "MISSING" in row, cp.stdout
    assert f"fix: {fix}" in cp.stdout
    assert cp.stdout.count("MISSING") == 1 and "preflight miss" in cp.stderr
    assert host.snapshot() == before and changes(host) == []
    dry = deploy(deployable, host, "--dry-run", ok=False)
    assert dry.returncode == 1 and "would stop: 1 preflight miss(es)" in dry.stdout and "[would run]" in dry.stdout
    assert host.snapshot() == before


