def test_a_deploy_through_the_ssh_transport_uses_only_the_persons_ssh(deployable, tmp_path):
    app, host = deployable.parent, prepared(tmp_path)
    fake, log = make_fake_ssh(tmp_path, host)
    env = {"AL_DEPLOY_LOCAL_HOST": "", "PATH": f"{fake}{os.pathsep}{os.environ['PATH']}"}
    cp = al("deploy", deployable, "--to", "testhost.invalid", env=env)
    checkout = host.root / "al/notes"
    assert git(checkout, "rev-parse", "HEAD") == git(app, "rev-parse", "main")
    assert git(checkout, "remote", "get-url", "origin") == str(host.root / "al/notes.git")
    for unit in UNITS:
        assert (host.root / ".config/systemd/user" / unit).is_file()
        assert re.search(rf"{re.escape(unit)}\s+enabled\s+active", cp.stdout), cp.stdout
    records = [json.loads(line) for line in log.read_text().splitlines()]
    scripts, pushes = 0, 0
    for argv in records:
        args, options = argv[1:], []
        while args and args[0].startswith("-"):
            options += args[:2] if args[0] == "-o" else args[:1]
            args = args[2:] if args[0] == "-o" else args[1:]
        assert args[0] == "testhost.invalid", argv
        assert not {"-i", "-l", "-p", "-F"} & set(options), argv
        assert not re.search(r"IdentityFile|User|StrictHostKeyChecking|Port|ProxyCommand", " ".join(options)), argv
        if args[1].startswith("git-receive-pack "):
            pushes += 1                                              # the local `git push testhost.invalid:<path>`
            assert str(host.root / "al/notes.git") in args[1]
        else:
            scripts += 1
            assert len(args) == 2 and args[1].startswith("sh -lc "), argv
            assert options == ["-T"], argv
    assert pushes == 1 and scripts >= 8
    status_cp = al("deploy", deployable, "--to", "testhost.invalid", "--status", env=env)
    assert "(same)" in status_cp.stdout
    bad = al("deploy", deployable, "--to=-oProxyCommand=x", env=env, ok=False)
    assert bad.returncode == 1 and "not a host" in bad.stderr and len(log.read_text().splitlines()) == len(records) + 2      # nothing was run for it


