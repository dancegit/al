def test_remote_is_read_or_change(tmp_path, capsys):
    host = make_host(tmp_path)
    remote = al_deploy.Remote(al_deploy.LocalTransport(str(host.root), host.path, "h"), dry_run=True)
    assert remote.read("echo hello", "a read").stdout == "hello\n"
    assert remote.change(": > made", "a change").returncode == 0 and not (host.root / "made").exists()
    assert remote.read("cat made", "after", after_change=True).stdout == ""
    al_deploy.put(remote, f"{host.root}/a/b", "text")
    assert remote.local_change(["false"], "local").returncode == 0
    out = capsys.readouterr().out
    assert "[read] host$ echo hello" in out and "[would run] host$ : > made" in out and "[would run] local$ false" in out
    assert "[would read] host$ cat made" in out and [kind for kind, _, _ in remote.log] == ["read", "change", "read", "change", "local"]
    real = al_deploy.Remote(al_deploy.LocalTransport(str(host.root), host.path, "h"))
    assert al_deploy.put(real, f"{host.root}/a/b", "text", "0600").returncode == 0
    assert (host.root / "a/b").read_text() == "text" and (host.root / "a/b").stat().st_mode & 0o777 == 0o600
    status_only = al_deploy.Remote(al_deploy.LocalTransport(str(host.root), host.path, "h"), read_only=True)
    with pytest.raises(RuntimeError):
        status_only.change("rm -rf x", "never")
    with pytest.raises(RuntimeError):
        status_only.local_change(["git", "push"], "never")


