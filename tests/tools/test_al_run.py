"""`al run LAYER /NAME [ARGS …]`: the dashboard's start path from the command line, on layers
generated by `al gen` (mock agent through --dry-run): a single command as a recorded run, a detached
start, an unknown name, the request key, and the startables of a layer with adopted workflows and
prompts (nothing in the code knows them)."""
from __future__ import annotations

import json
import re
import sys
import time
from pathlib import Path

import existing_setup
from conftest import KIT, al, status
from test_adopt import BASE

sys.path.insert(0, str(KIT / "dashboard"))
import dashboard  # noqa: E402

STARTED = re.compile(r"^run ([0-9a-f]{8}) started \(layer: (\S+), (workflow|command) (\S+)\)$", re.MULTILINE)


def run_ids(layer: Path) -> list[str]:
    agents = layer / "agents"
    return sorted(p.name for p in agents.iterdir() if p.is_dir() and re.fullmatch(r"[0-9a-f]{8}", p.name)) \
        if agents.is_dir() else []


def wait_finished(layer: Path, run_id: str, timeout: float = 300) -> dict:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            state = json.loads((layer / "agents" / run_id / "state.json").read_text())
            if state.get("status") in ("passed", "failed") and state.get("ended"):
                return state
        except (OSError, ValueError):
            pass
        time.sleep(0.3)
    raise AssertionError(f"run {run_id} did not finish")


def test_al_run_single_command_with_the_mock_agent(sibling, app):
    cp = al("run", sibling, "/tidy", "tidy", "the", "readme", "--dry-run")
    match = STARTED.search(cp.stdout)
    assert match, cp.stdout
    run_id = match.group(1)
    assert match.groups()[1:] == ("notes", "command", "tidy")
    assert "=== ADW summary ===" in cp.stdout and "status:    passed" in cp.stdout
    state = json.loads((sibling / "agents" / run_id / "state.json").read_text())
    assert state["status"] == "passed" and state["adw"] == "command:tidy" and state["prompt"] == "tidy the readme"
    assert state["plan"] and Path(state["plan"]).is_file() and state["ship"] == {}
    assert (sibling / "agents" / run_id / "request.md").read_text() == "tidy the readme\n"
    assert status(app) == ""


def test_al_run_detach_prints_the_run_id_and_returns(sibling):
    started = time.monotonic()
    cp = al("run", sibling, "/plan", "Add a search", "--dry-run", "--detach")
    match = STARTED.search(cp.stdout)
    assert match and cp.stdout.strip().splitlines()[-1] == match.group(0), cp.stdout
    assert "=== ADW summary ===" not in cp.stdout
    state = wait_finished(sibling, match.group(1))
    assert state["status"] == "passed" and state["adw"] == "command:plan"
    assert "[adw " in (sibling / "agents" / match.group(1) / "launch.log").read_text()
    assert time.monotonic() - started < 300


def test_al_run_unknown_name_exits_2_and_lists_known_names(sibling):
    cp = al("run", sibling, "/nope", "x", ok=False)
    assert cp.returncode == 2
    assert "no workflow or command named nope; known: /change, /plan, /tidy, /commit, /implement, /new-adw" in cp.stderr
    assert run_ids(sibling) == []
    cp = al("run", sibling, "change", "x", ok=False)
    assert cp.returncode == 2 and "start with /NAME" in cp.stderr


def test_al_run_same_request_key_twice_one_run(sibling):
    first = al("run", sibling, "/tidy", "once", "--dry-run", "--request-key", "my-key-0001")
    again = al("run", sibling, "/tidy", "once", "--dry-run", "--request-key", "my-key-0001")
    run_id = STARTED.search(first.stdout).group(1)
    assert f"run {run_id} was already started for this request key (layer: notes, command tidy)" in again.stdout
    assert run_ids(sibling) == [run_id]
    asked = al("run", sibling, "/tidy", "once", "--dry-run", ok=False)   # a new key, the same request
    assert asked.returncode == 4 and "pass --yes" in asked.stderr and run_ids(sibling) == [run_id]
    assert al("run", sibling, "/tidy", "once", "--dry-run", "--yes").returncode == 0
    assert len(run_ids(sibling)) == 2


def test_adopted_workflows_and_commands_are_startable(tmp_path):
    larder = existing_setup.build(tmp_path)
    layer = larder.with_name("larder.al")
    al("init", larder)
    (layer / "agentic.rkt").write_text(BASE)
    al("adopt", layer)
    al("gen", layer)
    catalog = dashboard.startables(dashboard.load_layer(layer, set()))
    workflows = {w["name"]: w for w in catalog["workflows"]}
    assert set(workflows) == {"change", "legacy-adw-plan-build", "legacy-adw-test"}
    assert workflows["legacy-adw-plan-build"]["summary"].startswith("runs the script legacy-adw-plan-build")
    commands = {c["name"]: c for c in catalog["commands"]}
    assert {"review-pr", "team-commit", "frontend-component", "plan", "implement"} <= set(commands)
    assert commands["review-pr"]["summary"].endswith("never ships")
    cp = al("run", layer, "/legacy-adw-plan-build", "Add a low-stock alert", "--dry-run")
    match = STARTED.search(cp.stdout)
    assert match and match.groups()[1:] == ("larder", "workflow", "legacy-adw-plan-build"), cp.stdout
    state = json.loads((layer / "agents" / match.group(1) / "state.json").read_text())
    assert state["status"] == "passed" and state["scripts"]["run"]["exit"] == 0
    assert status(larder) == ""
