"""End to end: a layer whose agentic.rkt declares a subscription usage threshold on (budget limits …)
is compiled and generated by tools/al, and its own runtime then stops a run at that threshold. No
LLM and no real usage data: the mock agent replays the CLI's `rate_limit_event` shape."""
from __future__ import annotations

import json
import time

from conftest import LAYER_TEMPLATE, al, sh

THRESHOLD = "(budget limits #:run-usd 5 #:limit-stop-percent 90 #:on-limit stop)"
WITH_THRESHOLD = LAYER_TEMPLATE.replace("  {placement}\n", "  {placement}\n  " + THRESHOLD + "\n")
RUN, NEXT = "11a17001", "11a17002"


def test_a_declared_usage_threshold_stops_the_run_of_a_generated_layer(app) -> None:
    assert THRESHOLD in WITH_THRESHOLD
    layer = app.parent / "notes.al"
    layer.mkdir()
    (layer / "agentic.rkt").write_text(WITH_THRESHOLD.format(root="../notes", placement="(layer sibling)"))
    al("gen", layer)

    # the language carried the three fields into the compiled layer, and al explain words them
    budget = json.loads((layer / "agentic-layer.json").read_text())["budget"]
    assert (budget["limitStopPercent"], budget["onLimit"], budget["limitWaitMinutes"]) == (90, "stop", 300)
    explained = al("explain", layer).stdout
    assert "90% of a subscription usage window" in explained and "handed to a person" in explained

    # the plan step's call reports the weekly window at 95%, resetting in two days (the run is a
    # subprocess on the real clock: the reset must lie in the future, so it is computed, not a constant)
    resets = int(time.time()) + 2 * 86400
    window = {"utilization": 0.95, "resetsAt": resets, "status": "allowed_warning"}
    events = [{"type": "system", "subtype": "init", "apiKeySource": "none"},
              {"type": "rate_limit_event", "rate_limit_info": {"status": "allowed_warning", "resetsAt": resets,
                                                               "rateLimitType": "seven_day",
                                                               "unifiedWindows": {"seven_day": window}}}]
    (layer / "mock" / "change").mkdir(parents=True)
    (layer / "mock" / "change" / "plan.json").write_text(json.dumps({
        "layer_files": {"specs/plan-threshold.md": "# Plan\n\nAdd a docstring.\n"},
        "files": {"NOTES.md": "work the plan step left in the worktree\n"},
        "output": "${layer_dir}/specs/plan-threshold.md", "cost": 0.5, "events": events}))

    script = layer / "adws" / "adw_change.py"
    cp = sh(["uv", "run", "--quiet", script, "Add a docstring", "--dry-run", "--adw-id", RUN], cwd=app)
    assert cp.returncode == 1, cp.stdout + cp.stderr
    state = json.loads((layer / "agents" / RUN / "state.json").read_text())
    assert [call["step"] for call in state["agent_calls"]] == ["plan"]          # build never started
    assert not (layer / "agents" / RUN / "build" / "raw.jsonl").exists()
    stopped = state["usage"]["stopped"]
    assert (stopped["cause"], stopped["window"], stopped["percent"], stopped["step"]) == ("threshold", "seven_day", 90, "build")
    reason = "limit:seven_day: 95% of the weekly subscription limit is used (threshold 90%, #:limit-stop-percent); resets "
    assert stopped["reason"].startswith(reason)
    assert state["ship"]["action"] == "handoff" and state["ship"]["stopped_at"] == "build"
    assert state["ship"]["reasons"][0].startswith("run-stopped:build: " + reason)
    assert reason in (layer / state["ship"]["target"]).read_text()                # the handover a person reads
    assert "STOPPED by limit:seven_day:" in cp.stdout + cp.stderr
    recorded = [json.loads(line) for line in (layer / "agents" / RUN / "events.jsonl").read_text().splitlines()]
    assert next(e for e in recorded if e["type"] == "run.start")["limits"]["limit_percent"] == 90
    assert [(e["cause"], e["percent"]) for e in recorded if e["type"] == "limit.stop"] == [("threshold", 90)]

    # and no new run starts while the window is over the threshold
    cp = sh(["uv", "run", "--quiet", script, "Another change", "--dry-run", "--adw-id", NEXT], cwd=app)
    assert cp.returncode == 3, cp.stdout + cp.stderr
    assert "#:limit-stop-percent" in cp.stderr and not (layer / "agents" / NEXT / "state.json").exists()
