"""End-to-end capture: start the app, walk e2e/scenario.py in headless Chromium, record proof.

    python e2e/capture.py

Writes e2e-results/NN-<name>.png for every step with a "screenshot" and e2e-results/session.webm
(a video of the whole session). Fails (exit 1) when a step's expectation does not hold, when the
page logs a console error or throws, or when the app does not start. Do not edit this file to make
a scenario pass: the scenario lives in e2e/scenario.py.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "e2e-results"
HOST, PORT = "127.0.0.1", 8000
BASE = f"http://{HOST}:{PORT}"
VIEWPORT = {"width": 1000, "height": 640}
STEP_PAUSE_MS = 1100     # after every step, so the video is watchable
SLOW_MO_MS = 80          # between browser operations
TYPE_DELAY_MS = 110      # between keys of a "type" step
EXPECT_TIMEOUT_S = 2.0
ACTIONS = ("goto", "fill", "type", "click", "press", "wait")
EXPECT_KEYS = {"text", "no_text", "visible", "hidden", "count", "style"}
# The container image installs Chromium here (world-readable); elsewhere Playwright's default is used.
if Path("/opt/pw").is_dir():
    os.environ.setdefault("PLAYWRIGHT_BROWSERS_PATH", "/opt/pw")

sys.path.insert(0, str(Path(__file__).resolve().parent))
from scenario import STEPS  # noqa: E402


class ScenarioError(AssertionError):
    pass


def start_app() -> subprocess.Popen:
    env = {**os.environ, "HOST": HOST, "PORT": str(PORT), "PYTHONUNBUFFERED": "1"}
    log = open(RESULTS / "app.log", "w")
    proc = subprocess.Popen([sys.executable, str(ROOT / "app.py")], cwd=ROOT, env=env, stdout=log, stderr=subprocess.STDOUT)
    deadline = time.monotonic() + 20
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise ScenarioError(f"the app exited with {proc.returncode} before serving; see e2e-results/app.log")
        try:
            with urllib.request.urlopen(BASE + "/", timeout=1) as response:
                if response.status == 200:
                    return proc
        except OSError:
            time.sleep(0.2)
    proc.kill()
    raise ScenarioError(f"the app did not answer on {BASE} within 20s")


def _strings(value) -> list[str]:
    return [value] if isinstance(value, str) else list(value)


def _visible_count(page, selector: str) -> int:
    return sum(1 for element in page.locator(selector).all() if element.is_visible())


def _problems(page, expect: dict) -> list[str]:
    problems = []
    body = page.locator("body").inner_text()
    for text in _strings(expect.get("text", [])):
        if text not in body:
            problems.append(f"page text does not contain {text!r}")
    for text in _strings(expect.get("no_text", [])):
        if text in body:
            problems.append(f"page text contains {text!r}")
    if "visible" in expect and _visible_count(page, expect["visible"]) == 0:
        problems.append(f"no visible element matches {expect['visible']!r}")
    if "hidden" in expect and _visible_count(page, expect["hidden"]) != 0:
        problems.append(f"an element matching {expect['hidden']!r} is visible")
    if "count" in expect:
        selector, wanted = expect["count"]["selector"], int(expect["count"]["visible"])
        got = _visible_count(page, selector)
        if got != wanted:
            problems.append(f"{got} visible elements match {selector!r}, expected {wanted}")
    if "style" in expect:
        style = expect["style"]
        got = page.locator(style["selector"]).first.evaluate(
            "(element, property) => getComputedStyle(element).getPropertyValue(property)", style["property"])
        if got.strip() != style["equals"]:
            problems.append(f"{style['selector']} {style['property']} is {got.strip()!r}, expected {style['equals']!r}")
    return problems


def check_expectations(page, expect: dict) -> None:
    unknown = set(expect) - EXPECT_KEYS
    if unknown:
        raise ScenarioError(f"unknown expect keys {sorted(unknown)}; known: {sorted(EXPECT_KEYS)}")
    deadline = time.monotonic() + EXPECT_TIMEOUT_S
    while True:
        problems = _problems(page, expect)
        if not problems:
            return
        if time.monotonic() >= deadline:
            raise ScenarioError("; ".join(problems))
        page.wait_for_timeout(100)


def run_step(page, step: dict) -> None:
    actions = [key for key in ACTIONS if key in step]
    if len(actions) != 1:
        raise ScenarioError(f"a step needs exactly one action of {ACTIONS}: {step!r}")
    action = actions[0]
    target = step[action]
    if action == "goto":
        page.goto(BASE + target, wait_until="networkidle")
    elif action == "fill":
        page.locator(target).first.fill(step["value"])
    elif action == "type":
        page.locator(target).first.click()
        page.locator(target).first.press_sequentially(step["value"], delay=TYPE_DELAY_MS)
    elif action == "click":
        page.locator(target).first.click()
        page.wait_for_load_state("networkidle")
    elif action == "press":
        page.locator(target).first.press(step["key"])
        page.wait_for_load_state("networkidle")
    elif action == "wait":
        page.wait_for_timeout(int(target))
    if step.get("expect"):
        check_expectations(page, step["expect"])


def main() -> int:
    from playwright.sync_api import sync_playwright

    shutil.rmtree(RESULTS, ignore_errors=True)
    RESULTS.mkdir()
    errors: list[str] = []
    failure = ""
    shots = 0
    app = start_app()
    video_dir = Path(tempfile.mkdtemp(prefix="e2e-video-"))
    try:
        with sync_playwright() as playwright:
            # --no-sandbox: Chromium's own sandbox needs user namespaces, which a rootless,
            # capability-dropped container does not grant; the container is the sandbox.
            browser = playwright.chromium.launch(headless=True, slow_mo=SLOW_MO_MS,
                                                 args=["--no-sandbox", "--disable-dev-shm-usage"])
            context = browser.new_context(viewport=VIEWPORT, record_video_dir=str(video_dir),
                                          record_video_size=VIEWPORT)
            page = context.new_page()
            page.on("console", lambda message: message.type == "error" and errors.append(f"console: {message.text}"))
            page.on("pageerror", lambda exc: errors.append(f"page error: {exc}"))
            for number, step in enumerate(STEPS, start=1):
                label = step.get("say") or next(f"{key} {step[key]}" for key in ACTIONS if key in step)
                try:
                    run_step(page, step)
                except Exception as exc:  # noqa: BLE001 — report the step, keep a screenshot of the failure
                    failure = f"step {number} ({label}): {exc}"
                    page.screenshot(path=str(RESULTS / f"{shots + 1:02d}-FAILED-step-{number}.png"))
                    print(f"FAIL  {failure}")
                    break
                if step.get("screenshot"):
                    shots += 1
                    page.screenshot(path=str(RESULTS / f"{shots:02d}-{step['screenshot']}.png"))
                print(f"ok    step {number}: {label}" + (f"  -> {shots:02d}-{step['screenshot']}.png" if step.get("screenshot") else ""))
                page.wait_for_timeout(STEP_PAUSE_MS)
            video = page.video
            context.close()
            browser.close()
            if video is not None:
                shutil.move(video.path(), RESULTS / "session.webm")
    finally:
        app.terminate()
        app.wait(timeout=10)
        shutil.rmtree(video_dir, ignore_errors=True)
    for error in errors:
        print(f"FAIL  {error}")
    if not (RESULTS / "session.webm").is_file():
        print("FAIL  no video was recorded")
        failure = failure or "no video"
    if failure or errors:
        print(f"e2e: FAILED ({len(STEPS)} steps, {shots} screenshots)")
        return 1
    print(f"e2e: passed, {len(STEPS)} steps, {shots} screenshots, video e2e-results/session.webm")
    return 0


if __name__ == "__main__":
    sys.exit(main())
