#!/usr/bin/env -S uv run --quiet --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Work dashboard of the `al` layer: a live, read-only view of what its agents are doing.

  uv run agentic/adws/dashboard.py [flags]       then open http://127.0.0.1:8765/

Declared in agentic.rkt as (dashboard local #:port 8765); generated by `al gen`: change agentic.rkt, not this file.
Flags given here are passed on and win over the declared ones (e.g. --port 9000 --open; the
dashboard's own --help lists them). AL_DASHBOARD_DRY_RUN=1 prints the command instead of running it.
"""
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LAYER = HERE.parent
KIND = 'local'
PORT = 8765
BIND = '127.0.0.1'
POLL_SECONDS = 0.75
# other layers on the same page, relative to this layer
ALSO = []
# environment variable holding the access token ("" = none)
TOKEN_ENV = ''
PODMAN_SOCKET = False


def given(args: list[str], flag: str) -> str | None:
    """The value of `flag` on the command line (also for `--flag=value`), "" for a bare flag, else None."""
    for index, arg in enumerate(args):
        if arg == flag:
            return args[index + 1] if index + 1 < len(args) and not args[index + 1].startswith("-") else ""
        if arg.startswith(flag + "="):
            return arg.split("=", 1)[1]
    return None


def loopback(host: str) -> bool:
    return host.strip("[]").lower() in ("localhost", "::1") or host.startswith("127.")


def also_layers() -> list[str]:
    found = []
    for entry in ALSO:
        path = (LAYER / entry).resolve()
        if path.is_dir():
            found.append(str(path))
        else:
            print(f"dashboard: #:also {entry!r} is not a directory ({path}); skipped", file=sys.stderr)
    return found


def command(args: list[str]) -> tuple[list[str], dict[str, str]]:
    env = dict(os.environ)
    if KIND == "podman":
        argv = [str(HERE / "dashboard" / "run-in-podman.sh")]
        argv += [] if given(args, "--port") is not None else ["--port", str(PORT)]
        argv += [] if given(args, "--poll") is not None else ["--poll", str(POLL_SECONDS)]
        argv += ["--podman-socket"] if PODMAN_SOCKET and given(args, "--podman-socket") is None else []
        return [*argv, *args, str(LAYER), *also_layers()], env
    argv = [sys.executable, str(HERE / "dashboard" / "dashboard.py"), "--layer", str(LAYER)]
    for path in also_layers():
        argv += ["--layer", path]
    bind = given(args, "--bind") or BIND
    argv += [] if given(args, "--port") is not None else ["--port", str(PORT)]
    argv += [] if given(args, "--bind") is not None else ["--bind", BIND]
    argv += [] if given(args, "--poll") is not None else ["--poll", str(POLL_SECONDS)]
    if TOKEN_ENV and given(args, "--token") is None:
        token = os.environ.get(TOKEN_ENV, "").strip()
        if token:
            env["AL_DASHBOARD_TOKEN"] = token   # through the environment: a token on argv shows in `ps`
        elif not loopback(bind):
            sys.exit(f"dashboard: binding to {bind} needs an access token, but ${TOKEN_ENV} is not set; "
                     f"export {TOKEN_ENV}=<a long random string> (or bind to 127.0.0.1)")
    return [*argv, *args], env


def main() -> int:
    argv, env = command(sys.argv[1:])
    if os.environ.get("AL_DASHBOARD_DRY_RUN"):
        print(json.dumps({"argv": argv, "token": bool(env.get("AL_DASHBOARD_TOKEN"))}))
        return 0
    os.execve(argv[0], argv, env)
    return 1


if __name__ == "__main__":
    sys.exit(main())
