def _case(make_layer, app_repo, reason: str) -> tuple[Path, str]:
    """A layer and a run id that eligible() refuses with `reason`."""
    demo = {"name": "demo", "agent": "mock", "review": "policy", "environment": ["worktree"], "classes": ["chore"],
            "steps": [{"name": "build", "kind": "run", "command": "build"},
                      {"name": "test", "kind": "check", "cmd": "test"},
                      {"name": "review", "kind": "review"}, {"name": "ship", "kind": "ship"}]}
    options: dict = {}
    if reason == "off":
        options["settings"] = {"enabled": False}
    if reason == "layer-change":
        options["adws"] = [{**demo, "changes": "layer"}]
    if reason == "no-ship-step":
        options["adws"] = [{**demo, "steps": demo["steps"][:-1]}]
    if reason == "name-taken":
        options["adws"] = [demo, {**demo, "name": "integrate"}]
    if reason == "protected-path-in-repo":
        options["extra"] = {"layer": {"id": "in-repo", "kind": "in-repo", "dir": "agentic", "status": "stable"}}
    layer = conflict_layer(make_layer, app_repo, **options)
    run_id = RUN
    files = dict(RUN_FILES)
    kwargs: dict = {}
    if reason == "not-handed-over":
        kwargs["status"] = "passed"
    if reason == "review-rejected":
        kwargs["rejected"] = True
    if reason == "not-a-conflict":
        kwargs["reasons"] = ("diff-too-large:3000>2000",)
    if reason == "protected-path":
        files["deploy/release.cfg"] = "channel = beta\n"
    if reason == "protected-path-in-repo":
        files["agentic/notes.md"] = "a change to the layer\n"
    state = handed_over_run(layer, app_repo, RUN, files, **kwargs)
    if reason != "landed":
        move_main(app_repo)
    if reason == "unknown-run":
        run_id = "deadbeef"
    if reason == "settled":
        (layer / "agents" / RUN / "settlement.json").write_text(json.dumps({"as": "abandoned", "who": "Ada Example"}))
    if reason == "branch-missing":
        git(app_repo, "branch", "-D", state["branch"])
    if reason == "branch-changed":
        commit_on(app_repo, state["branch"], {"note.txt": "a person was here\n"}, "a person's commit")
    if reason == "landed":
        git(app_repo, "update-ref", "refs/heads/main", state["ship"]["commit"])
    return layer, run_id


@pytest.mark.parametrize("reason", ["off", "unknown-run", "not-handed-over", "settled", "review-rejected",
                                    "not-a-conflict", "layer-change", "no-ship-step", "name-taken", "branch-missing",
                                    "branch-changed", "landed", "protected-path", "protected-path-in-repo"])
def test_refuses_each_reason(make_layer, app_repo, reason):
    layer, run_id = _case(make_layer, app_repo, reason)
    with pytest.raises(integrate.IntegrateError) as caught:
        integrate.eligible(ir.load(layer), run_id)
    expected = "protected-path" if reason.startswith("protected-path") else reason
    assert caught.value.reason == expected, str(caught.value)
    assert str(caught.value).startswith(f"integrate:{expected}: ")
    if reason == "protected-path":
        assert "deploy/release.cfg" in caught.value.message
    if reason == "protected-path-in-repo":
        assert "agentic/notes.md" in caught.value.message
    if reason == "branch-changed":
        assert "a person changed" in caught.value.message
    assert expected in integrate.REASONS


