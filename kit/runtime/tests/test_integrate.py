# ---------------------------------------------------------------- the report and the records

def _integration_state(layer: Path, run_id: str, files: list[tuple[str, bool]]) -> None:
    directory = layer / "agents" / run_id
    directory.mkdir(parents=True)
    (directory / "state.json").write_text(json.dumps({
        "adw_id": run_id, "adw": "integrate", "status": "passed",
        "integration": {"run": "f0000009", "conflicts": [{"file": name, "generated": generated, "regenerate": "",
                                                          "touched_by": []} for name, generated in files]}}))


def test_conflict_report_counts_files_and_pairs(make_layer, app_repo):
    layer = conflict_layer(make_layer, app_repo)
    assert integrate.report_lines(integrate.conflict_report(ir.load(layer))) == ["no integration had a conflict yet"]
    _integration_state(layer, "b0000001", [("stock.py", False), ("INDEX.md", True)])
    _integration_state(layer, "b0000002", [("stock.py", False), ("INDEX.md", True), ("prices.py", False)])
    _integration_state(layer, "b0000003", [("stock.py", False)])
    (layer / "agents" / "b0000004").mkdir()
    (layer / "agents" / "b0000004" / "state.json").write_text(json.dumps({"adw_id": "b0000004", "adw": "demo"}))
    report = integrate.conflict_report(ir.load(layer))
    assert report["integrations"] == 3
    assert report["files"] == [{"file": "stock.py", "times": 3, "generated": False},
                               {"file": "INDEX.md", "times": 2, "generated": True},
                               {"file": "prices.py", "times": 1, "generated": False}]
    assert report["pairs"] == [{"files": ["INDEX.md", "stock.py"], "times": 2},
                               {"files": ["INDEX.md", "prices.py"], "times": 1},
                               {"files": ["prices.py", "stock.py"], "times": 1}]
    lines = integrate.report_lines(report)
    assert lines[0] == "3 integrations had conflicts"
    assert any(line.strip().startswith("stock.py") and "3 times" in line for line in lines)
    assert any("INDEX.md + stock.py" in line and "2 times" in line for line in lines)
    assert lines[-1] == ("a file that conflicts often: split it, or mark it generated in "
                         "templates/integrate.json")


