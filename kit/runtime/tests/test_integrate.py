def test_integration_adw_shape(make_layer, app_repo):
    layer = conflict_layer(make_layer, app_repo, extra={"promptInputs": [
        {"id": "cli", "kind": "cli", "status": "stable", "allowStdin": False}]})
    handed_over_run(layer, app_repo, RUN)
    move_main(app_repo)
    loaded = ir.load(layer)
    original = integrate.eligible(loaded, RUN)
    base = loaded.adw("demo")
    adw = integrate.integration_adw(loaded, original, integrate.settings(layer))
    assert adw["name"] == "integrate"
    assert adw["description"] == f"integrate run {RUN} onto main"
    assert adw["integration"] == {"run": RUN, "branch": original.branch, "tip": original.tip, "target": "main",
                                  "workflow": "demo"}
    assert [(s["kind"], s["name"]) for s in adw["steps"]] == [
        ("integrate", "prepare"), ("integrate", "resolve"), ("check", "test"), ("review", "review"), ("ship", "ship")]
    assert adw["steps"][2]["whenAffected"] is True and adw["steps"][2]["cmd"] == "test"
    assert adw["steps"][3] == next(s for s in base["steps"] if s["kind"] == "review")
    assert adw["steps"][4] == next(s for s in base["steps"] if s["kind"] == "ship")
    assert (adw["agent"], adw["review"], adw["environment"]) == (base["agent"], base["review"], base["environment"])
    assert "deliverTo" not in adw and adw["input"] == ["cli"] and adw["changes"] == "codebase"
    assert "whenAffected" not in base["steps"][2], "the layer's own workflow is not changed"
    with_person = integrate.integration_adw(loaded, original, {**integrate.settings(layer), "approval": "person"})
    assert [s["name"] for s in with_person["steps"]] == ["prepare", "resolve", "test", "review", "approve", "ship"]
    assert with_person["steps"][4] == {"kind": "integrate", "name": "approve", "action": "approve"}
    loaded.ir["adws"].append(adw)
    assert loaded.validate_adw("integrate") is adw


