def test_integration_record_keeps_earlier_ones(make_layer, app_repo):
    layer = conflict_layer(make_layer, app_repo)
    handed_over_run(layer, app_repo, RUN)
    loaded = ir.load(layer)
    assert integrate.read_record(loaded, RUN) is None
    for index in range(7):
        integrate.write_record(loaded, RUN, run=f"c000000{index}", status="failed", why=f"attempt {index}",
                               target="main", by="cli")
    record = integrate.read_record(loaded, RUN)
    assert (record["run"], record["status"], record["why"], record["commit"]) == ("c0000006", "failed", "attempt 6", "")
    assert [item["run"] for item in record["previous"]] == [f"c000000{i}" for i in (5, 4, 3, 2, 1)]
    assert all("previous" not in item for item in record["previous"])
    integrate.write_record(loaded, RUN, run="c0000006", status="landed", why="", commit="abc", target="main", by="cli")
    again = integrate.read_record(loaded, RUN)
    assert again["status"] == "landed" and [item["run"] for item in again["previous"]][0] == "c0000005", \
        "an update of the same integration replaces its record"
    assert oct((layer / "agents" / RUN / "integration.json").stat().st_mode & 0o777) == "0o600"


