"""Helpers for the integration tests (adw_modules/integrate.py): an application with invented names,
a handed-over run with a real branch, and a `main` that moved since.

The application has `stock.py` (a function `total(items)`), `INDEX.md` (generated by `./index.sh`,
which lists the `*.py` files), `tests/test_stock.py`, `deploy/release.cfg` (a protected path) and
`test.sh`. Its checkout is on a side branch, so `main` is not checked out. The layer has the mock
agent, a worktree environment, an auto review that merges, and the workflow `demo` (plan, build,
check `test`, review, ship)."""
from __future__ import annotations

import contextlib
import io
import json
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from adw_modules import integrate

RUNTIME = Path(__file__).resolve().parents[1]
# adws/integrate.py as `al gen` writes it, importing this checkout's runtime instead of the layer's copy
ENTRY_SCRIPT = ("import sys\nfrom pathlib import Path\n"
                f"sys.path.insert(0, {str(RUNTIME)!r})\n"
                "from adw_modules import integrate\n"
                "sys.exit(integrate.main(Path(__file__).resolve().parent.parent, sys.argv[1:]))\n")
STOCK = "def total(items):\n    return sum(items)\n"
INDEX_HEADER = "<!-- Generated by ./index.sh; DO NOT EDIT -->"
INDEX_SH = ("#!/bin/sh\n# writes INDEX.md: one line per python file\n"
            "{ echo '" + INDEX_HEADER + "'; echo '# Index'; echo; "
            "for f in *.py; do echo \"- $f\"; done; } > INDEX.md\n")
TEST_STOCK = "from stock import total\n\n\ndef test_total():\n    assert total([1, 2]) == 3\n"
RELEASE = "channel = stable\n"

# the two sides of the usual conflict: the run adds a discount, main adds a tax
RUN_STOCK = "def total(items, discount=0):\n    return sum(items) - discount\n"
MAIN_STOCK = "def total(items, tax=0):\n    return sum(items) + tax\n"
BOTH_STOCK = "def total(items, discount=0, tax=0):\n    return sum(items) - discount + tax\n"
RUN_FILES = {"stock.py": RUN_STOCK, "shelf.py": "SHELF = 1\n", "INDEX.md": None,
             "tests/test_discount.py": "from stock import total\n\n\ndef test_discount():\n"
                                       "    assert total([5], discount=1) == 4\n"}
MAIN_FILES = {"stock.py": MAIN_STOCK, "shop.py": "SHOP = 1\n", "INDEX.md": None,
              "tests/test_tax.py": "from stock import total\n\n\ndef test_tax():\n    assert total([5], tax=1) == 6\n"}
BOTH_INDEX = INDEX_HEADER + "\n# Index\n\n- app.py\n- shelf.py\n- shop.py\n- stock.py\n"
REPORT = {"resolved": [{"file": "stock.py", "sides": "the run added a discount, main added a tax",
                        "resolution": "one total() that takes both"}],
          "regenerated": [{"file": "INDEX.md", "command": "./index.sh"}], "undecidable": []}


def git(repo: Path, *args: str, check: bool = True) -> str:
    result = subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.org", *args],
                            capture_output=True, text=True, timeout=60)
    if check:
        assert result.returncode == 0, result.stderr
    return result.stdout.strip()


def index_of(names: list[str]) -> str:
    """INDEX.md as ./index.sh writes it for these python files."""
    return INDEX_HEADER + "\n# Index\n\n" + "".join(f"- {name}\n" for name in sorted(names))


def _write(tree: Path, files: dict[str, Any]) -> None:
    for name, content in files.items():
        if name == "INDEX.md" and content is None:
            continue
        target = tree / name
        if content is None:
            target.unlink(missing_ok=True)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        if name.endswith(".sh"):
            target.chmod(0o755)
    if "INDEX.md" in files and files["INDEX.md"] is None:   # regenerated, as a person or an agent would
        subprocess.run(["./index.sh"], cwd=tree, check=True, capture_output=True, timeout=30)


def commit_on(app: Path, branch: str, files: dict[str, Any], message: str, new_from: str = "") -> str:
    """A commit on `branch` made in a throwaway worktree (the application's checkout is not touched).
    A value of None deletes the file; `"INDEX.md": None` regenerates it with ./index.sh. With
    `new_from` the branch is created from that ref first."""
    if not new_from and git(app, "symbolic-ref", "--short", "HEAD", check=False) == branch:
        _write(app, files)      # the branch is checked out in the application: commit there
        git(app, "add", "-A")
        git(app, "commit", "-q", "-m", message)
        return git(app, "rev-parse", "HEAD")
    tree = Path(tempfile.mkdtemp(prefix="helper-", dir=app.parent))
    tree.rmdir()
    if new_from:
        git(app, "worktree", "add", "-q", "-b", branch, str(tree), new_from)
    else:
        git(app, "worktree", "add", "-q", str(tree), branch)
    _write(tree, files)
    git(tree, "add", "-A")
    git(tree, "commit", "-q", "-m", message)
    commit = git(tree, "rev-parse", "HEAD")
    git(app, "worktree", "remove", "--force", str(tree))
    return commit


def conflict_layer(make_layer, app_repo: Path, *, approval: str = "", settings: dict[str, Any] | None = None,
                   test_run: str = "./test.sh", main_checked_out: bool = False, ship: str = "merge",
                   extra: dict[str, Any] | None = None, adws: list[dict[str, Any]] | None = None) -> Path:
    """The layer and the application described in the module docstring. `settings` is written as
    templates/integrate.json (default: INDEX.md is generated by ./index.sh); `approval="person"`
    asks for a person before ship; `test_run` replaces what the check `test` runs."""
    demo = {"name": "demo", "agent": "mock", "review": "policy", "environment": ["worktree"],
            "classes": ["chore", "bug", "feature", "patch"], "steps": [
                {"name": "plan", "kind": "run", "command": "plan"},
                {"name": "build", "kind": "run", "command": "build"},
                {"name": "test", "kind": "check", "cmd": "test"},
                {"name": "review", "kind": "review", "patch": "patch", "implement": "implement"},
                {"name": "ship", "kind": "ship"}]}
    overrides = {
        "agents": [{"id": "mock", "kind": "mock", "scriptDir": "mock", "status": "stable", "timeout": 20}],
        "commands": [{"name": n, "template": t, "modelSet": "base", "output": o} for n, t, o in (
            ("plan", "plan", "path"), ("build", "build", "text"), ("review", "review", "json"),
            ("patch", "plan-patch", "text"), ("implement", "implement", "text"))],
        "codebase": {"paths": {"protected": ["deploy"], "tests": ["tests"]},
                     "commands": [{"name": "test", "run": test_run, "timeout": 30}]},
        "reviews": [{"id": "policy", "kind": "auto", "status": "stable", "command": "review", "reviewers": 1,
                     "maxRetries": 0, "artefacts": [], "allowedClasses": ["chore", "bug", "feature", "patch"],
                     "blockProtectedPaths": True, "maxDiffLines": 2000, "requireChecks": ["test"], "ship": ship,
                     "deployCmd": ""}],
        "environments": [{"id": "worktree", "kind": "worktree", "dir": "trees", "copyFiles": [],
                          "portBase": 27700, "portsPerRun": 0, "keep": "never", "status": "stable"}],
        "forge": {"id": "none", "kind": "none", "status": "stable", "remote": ""},
        "concurrency": {"maxRuns": 8, "maxAgents": 4, "maxChecks": 4, "waitSeconds": 60},
        "adws": adws if adws is not None else [demo],
        **(extra or {}),
    }
    layer = make_layer(overrides)
    _write(app_repo, {"stock.py": STOCK, "index.sh": INDEX_SH, "tests/test_stock.py": TEST_STOCK,
                      "deploy/release.cfg": RELEASE, "INDEX.md": None})
    git(app_repo, "add", "-A")
    git(app_repo, "commit", "-q", "-m", "the pantry: stock, its index and its tests")
    if not main_checked_out:
        git(app_repo, "checkout", "-q", "-b", "work")
    chosen = dict(settings) if settings is not None else {"generated": [{"path": "INDEX.md", "regenerate": "./index.sh"}]}
    if approval:
        chosen["approval"] = approval
    if chosen:
        (layer / "templates").mkdir(exist_ok=True)
        (layer / integrate.SETTINGS_FILE).write_text(json.dumps({"version": 1, **chosen}, indent=2) + "\n",
                                                     encoding="utf-8")
    (layer / "adws").mkdir(exist_ok=True)
    (layer / "adws" / "integrate.py").write_text(ENTRY_SCRIPT, encoding="utf-8")
    # the kit prompt, as `al gen` writes it into every layer (the test needs only its arguments)
    (layer / "commands").mkdir(exist_ok=True)
    (layer / "commands" / "resolve-conflicts.md").write_text("# resolve-conflicts\nBRIEF: $1\nCONFLICTS: $2\n",
                                                             encoding="utf-8")
    return layer


def handed_over_run(layer: Path, app: Path, run_id: str, files: dict[str, Any] | None = None, *,
                    reasons: tuple[str, ...] = ("merge-conflict:ship: git merge --no-edit main failed: CONFLICT",),
                    rejected: bool = False, title: str = "Give stock a discount", klass: str = "chore",
                    base: str = "main", status: str = "handed-over") -> dict[str, Any]:
    """A run of `demo` that ended handed over: `files` committed on its branch `chore/<id>-…` cut
    from `base` (the old main), and agents/<id>/state.json and request.md as the runner leaves them."""
    files = dict(RUN_FILES if files is None else files)
    slug = "-".join("".join(c for c in word if c.isalnum()) for word in title.lower().split()[:6])
    branch = f"{klass}/{run_id}-{slug}"
    commit = commit_on(app, branch, files, f"{klass}: {title} [adw {run_id}]", new_from=base)
    run_dir = layer / "agents" / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    plan = layer / "specs" / f"plan-{run_id}.md"
    plan.parent.mkdir(exist_ok=True)
    plan.write_text(f"# Plan: {title}\n\n## Acceptance Criteria\n\n- it works\n", encoding="utf-8")
    verdict = {"success": not rejected, "mode": "auto", "summary": "wrong" if rejected else "looks right",
               "issues": ([{"severity": "blocker", "description": "wrong", "resolution": "fix"}] if rejected else [])}
    all_reasons = [*(["review-rejected"] if rejected else []), *reasons]
    state = {
        "adw_id": run_id, "adw": "demo", "prompt": f"{title}\n\nThe total can take a discount.", "source": "cli",
        "klass": klass, "class_fixed": True, "status": status, "branch": branch, "worktree": "",
        "plan": str(plan), "started": "2026-11-16T09:00:00+00:00", "ended": "2026-11-16T09:10:00+00:00",
        "steps": [{"name": n, "kind": k, "status": "rejected" if rejected and n == "review" else "passed",
                   "attempts": 1, "started": "", "ended": "", "detail": ""}
                  for n, k in (("plan", "run"), ("build", "run"), ("test", "check"), ("review", "review"),
                               ("ship", "ship"))],
        "checks": {"test": {"exit": 0, "log": f"agents/{run_id}/checks/test.log"}},
        "review": {"mode": "auto", "verdict": verdict, "rounds": [{"round": 1, "reviewers": [verdict],
                                                                   "verdict": verdict}]},
        "ship": {"action": "pr", "shipped": False, "commit": commit, "reasons": all_reasons,
                 "handed_over": all_reasons if status == "handed-over" else [],
                 "target": f"agents/{run_id}/PR.md", "pr": None},
    }
    (run_dir / "state.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    (run_dir / "request.md").write_text(state["prompt"] + "\n", encoding="utf-8")
    (run_dir / "PR.md").write_text(f"# {klass}: {title}\n", encoding="utf-8")
    return state


def move_main(app: Path, files: dict[str, Any] | None = None, message: str = "feature: Add a tax [adw a0000003]",
              branch: str = "main") -> str:
    """A commit on `main` made after the run's branch was cut."""
    return commit_on(app, branch, dict(MAIN_FILES if files is None else files), message)


def resolve_script(layer: Path, files: dict[str, str] | None = None, report: dict[str, Any] | None = None,
                   **more: Any) -> Path:
    """mock/integrate/resolve.json: what the mock agent does at the resolve step. `files` are written
    verbatim into the worktree; the output ends in the fenced json report."""
    files = {"stock.py": BOTH_STOCK, "INDEX.md": BOTH_INDEX} if files is None else files
    report = REPORT if report is None else report
    path = layer / "mock" / "integrate" / "resolve.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    output = "Resolved the conflicts.\n\n```json\n" + json.dumps(report, indent=2) + "\n```\n"
    path.write_text(json.dumps({"raw_files": files, "output": output, **more}), encoding="utf-8")
    return path


def review_script(layer: Path, success: bool = True) -> Path:
    path = layer / "mock" / "integrate" / "review-1.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    verdict = {"success": success, "summary": "the resolutions are right" if success else "the resolution is wrong",
               "issues": [] if success else [{"severity": "blocker", "description": "the resolution drops the tax",
                                              "resolution": "keep both"}]}
    path.write_text(json.dumps({"output": json.dumps(verdict)}), encoding="utf-8")
    return path


def integrate_main(layer: Path, *argv: str) -> tuple[int, str]:
    """integrate.main with its output captured: (exit code, stdout + stderr)."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = integrate.main(layer, list(argv))
    return code, out.getvalue() + err.getvalue()


def state_of(layer: Path, run_id: str) -> dict[str, Any]:
    return json.loads((layer / "agents" / run_id / "state.json").read_text(encoding="utf-8"))


def record_of(layer: Path, run_id: str, name: str = "integration.json") -> dict[str, Any]:
    return json.loads((layer / "agents" / run_id / name).read_text(encoding="utf-8"))


def events_of(layer: Path, run_id: str) -> list[dict[str, Any]]:
    path = layer / "agents" / run_id / "events.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def integration_runs(layer: Path) -> list[str]:
    """Ids of the integration runs of the layer, oldest first."""
    found = []
    for path in sorted((layer / "agents").glob("*/state.json"), key=lambda p: p.stat().st_mtime):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("adw") == "integrate":
            found.append(str(data["adw_id"]))
    return found


def refs(app: Path) -> str:
    return git(app, "for-each-ref", "--format=%(refname) %(objectname)")
