#!/usr/bin/env -S uv run --quiet --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["playwright>=1.49"]
# ///
"""Record the work dashboard live, in a real browser, while three workflow runs execute.

    kit/dashboard/demo/live_demo.py [--out docs/demo/dashboard] [--workdir DIR] [--setup-only] [--keep]

What it sets up (in a temp directory, never in this repository):
  cart/      a tiny git repository: cart.py, tests/, tools/lint.py, tools/run_tests.py (slow, coloured)
  cart.al/   its agentic layer, generated by `tools/al gen` from demo/layer.rkt.in:
             planning, commit and the two reviewers run on the mock agent (no LLM, no cost); the build
             step runs demo/replay_agent.py, a scripted stand-in CLI agent that streams a Claude-format
             transcript while it really edits the worktree; lint and test run for real in a podman
             container (docker.io/library/python:3.12-slim); (concurrency slots #:max-runs 2).
Then it starts the dashboard, opens it in Chrome with Playwright recording video, starts three runs
a few seconds apart (the third waits for a run slot; the third also makes a deliberate mistake that
its test check catches and a resolve agent fixes), clicks through what happens, and converts the
recording into live.mp4 and live.gif with ffmpeg.

Needs: racket (for al gen), uv, git, podman, ffmpeg, Google Chrome, and Playwright's small ffmpeg
build for video capture (`uv run --with playwright playwright install ffmpeg`).
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DASHBOARD = HERE.parent / "dashboard.py"
CHROME = os.environ.get("AL_DASHBOARD_CHROME") or shutil.which("google-chrome") or shutil.which("chromium")

CART = '''"""A shopping cart. Prices are integers in cents."""
from dataclasses import dataclass, field


@dataclass
class Item:
    name: str
    price: int


@dataclass
class Cart:
    items: list[Item] = field(default_factory=list)

    def total(self) -> int:
        return sum(item.price for item in self.items)

    def add(self, item: Item) -> None:
        self.items.append(item)
'''

RUN_TESTS = r'''"""Run every test_* function in tests/test_*.py, slowly, with coloured progress (a stand-in for a real suite)."""
import importlib.util, sys, time, traceback
from pathlib import Path

fast, colour = "--fast" in sys.argv, "--no-color" not in sys.argv
green, red, dim, bold, off = ("\x1b[32m", "\x1b[31m", "\x1b[2m", "\x1b[1m", "\x1b[0m") if colour else ("",) * 5
sys.path.insert(0, ".")
failed = passed = 0
for path in sorted(Path("tests").glob("test_*.py")):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for name in sorted(n for n in dir(module) if n.startswith("test_")):
        time.sleep(0 if fast else 0.45)
        try:
            getattr(module, name)()
            passed += 1
            print(f"{green}PASS{off} {path.name}::{name}", flush=True)
        except Exception:
            failed += 1
            print(f"{red}{bold}FAIL{off} {path.name}::{name}\n{dim}{traceback.format_exc()}{off}", flush=True)
print(f"{bold}{passed} passed, {failed} failed{off}")
sys.exit(1 if failed else 0)
'''

LINT = r'''"""A slow stand-in linter: compiles every Python file and checks line length."""
import py_compile, sys, time
from pathlib import Path

bad = 0
for path in sorted(Path(".").rglob("*.py")):
    time.sleep(0.35)
    py_compile.compile(str(path), doraise=True)
    long = [n for n, line in enumerate(path.read_text().splitlines(), 1) if len(line) > 120]
    bad += len(long)
    print(f"checked {path}" + (f": lines too long {long}" if long else ""), flush=True)
print("lint: ok" if not bad else f"lint: {bad} problem(s)")
sys.exit(1 if bad else 0)
'''

TEST_CART = '''from cart import Cart, Item


def test_empty_cart_costs_nothing():
    assert Cart().total() == 0


def test_total_adds_prices():
    cart = Cart()
    cart.add(Item("pen", 150))
    cart.add(Item("pad", 350))
    assert cart.total() == 500


def test_items_keep_their_order():
    cart = Cart()
    cart.add(Item("a", 1))
    cart.add(Item("b", 2))
    assert [i.name for i in cart.items] == ["a", "b"]
'''

LLM_TXT = """# cart

A tiny shopping-cart library used to demonstrate the al work dashboard.

## Commands

| name | command | proves what | evidence |
|---|---|---|---|
| lint | python3 tools/lint.py | every Python file compiles; no line over 120 characters | tools/lint.py |
| test | python3 tools/run_tests.py | every test_* function in tests/ passes | tools/run_tests.py |
"""

PROMPTS = [
    "Add a percentage discount to the cart: Cart.discounted(percent) returns the total after the discount, in cents.",
    "Charge 4.95 shipping below a 50.00 subtotal and ship free from 50.00 upwards.",
    "Make the cart total robust to rounding: it must always be a whole number of cents.",
]


def sh(argv: list[str], cwd: Path | None = None, check: bool = True, **kw) -> subprocess.CompletedProcess:
    return subprocess.run(argv, cwd=cwd, check=check, text=True, capture_output=True, **kw)


def setup(work: Path) -> Path:
    app, layer = work / "cart", work / "cart.al"
    for path, text in {"cart.py": CART, "tests/__init__.py": "", "tests/test_cart.py": TEST_CART,
                       "tools/run_tests.py": RUN_TESTS, "tools/lint.py": LINT, "README.md": "# cart\n\nA demo library.\n",
                       ".gitignore": "__pycache__/\n*.pyc\n"}.items():
        (app / path).parent.mkdir(parents=True, exist_ok=True)
        (app / path).write_text(text)
    sh(["git", "init", "-q", "-b", "main"], app)
    sh(["git", "add", "-A"], app)
    sh(["git", "-c", "user.name=demo", "-c", "user.email=demo@localhost", "commit", "-qm", "cart"], app)
    layer.mkdir(parents=True)
    source = (HERE / "layer.rkt.in").read_text().replace("@APP@", str(app)).replace("@REPLAY@", str(HERE / "replay_agent.py"))
    (layer / "agentic.rkt").write_text(source)
    (layer / "LLM.txt").write_text(LLM_TXT)
    mock = layer / "mock"
    mock.mkdir()
    (mock / "commit.json").write_text(json.dumps({"commit": True, "output": "Committed the change with a one-line message."}))
    # the rounding run's first test attempt fails; this scripted resolve agent restores a correct total()
    (mock / "test-resolve-1.json").write_text(json.dumps({"files": {"cart.py": CART}, "output": "Restored total(): prices are already whole cents."}))
    done = sh([str(ROOT / "tools" / "al"), "gen", str(layer)], check=False)
    if done.returncode != 0:
        sys.exit(f"al gen failed:\n{done.stdout}\n{done.stderr}")
    return layer


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def convert(video: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    mp4, gif = out / "live.mp4", out / "live.gif"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(video), "-vf", "fps=12,scale=1280:800:flags=lanczos",
                    "-c:v", "libx264", "-preset", "slow", "-crf", "30", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
                    str(mp4)], check=True)
    subprocess.run([sys.executable, str(HERE / "gif.py"), str(video), str(gif), "--max-bytes", "2500000"], check=True)
    print(f"{mp4} {mp4.stat().st_size} bytes\n{gif} {gif.stat().st_size} bytes")


def record(layer: Path, out: Path, work: Path) -> None:
    from playwright.sync_api import sync_playwright

    port = free_port()
    dashboard = subprocess.Popen([sys.executable, str(DASHBOARD), "--layer", str(layer), "--port", str(port), "--poll", "0.5"],
                                 stdout=subprocess.DEVNULL, stderr=(work / "dashboard.log").open("w"))
    runs: list[subprocess.Popen] = []
    base = f"http://127.0.0.1:{port}"
    try:
        for _ in range(50):
            try:
                socket.create_connection(("127.0.0.1", port), timeout=0.2).close()
                break
            except OSError:
                time.sleep(0.1)
        with sync_playwright() as p:
            browser = p.chromium.launch(executable_path=CHROME, headless=True)
            context = browser.new_context(viewport={"width": 1280, "height": 800}, record_video_dir=str(work / "video"),
                                          record_video_size={"width": 1280, "height": 800}, device_scale_factor=1)
            page = context.new_page()
            page.goto(f"{base}/#/now")
            page.wait_for_selector("#conn.conn-live")
            started = time.monotonic()

            def start(index: int) -> None:
                log = (work / f"run-{index + 1}.log").open("w")
                runs.append(subprocess.Popen(["uv", "run", "--quiet", "adws/adw_change.py", PROMPTS[index]], cwd=layer,
                                             stdout=log, stderr=subprocess.STDOUT))

            def at(seconds: float) -> None:
                time.sleep(max(0.0, seconds - (time.monotonic() - started)))

            at(1.5); start(0)
            at(3.5); start(1)
            at(5.5); start(2)
            page.wait_for_selector(".run-card.waiting", timeout=20000)           # the third run waits for a slot
            at(7.0)
            page.locator(".run-card", has_text="percentage discount").click()   # into the first run
            page.wait_for_selector(".g-node.st-running[data-step='build']", timeout=20000)
            at(8.5)
            page.click(".g-node[data-step='build']")                            # its transcript, following live
            page.wait_for_selector(".ev.k-tool")
            page.wait_for_selector(".g-node.st-running[data-step='lint'], .g-node.st-running[data-step='test']", timeout=30000)
            page.click(".g-node[data-step='lint']")
            page.wait_for_selector(".g-node.st-running[data-step='test'], .g-node.st-passed[data-step='test']", timeout=30000)
            page.click(".g-node[data-step='test']")                             # the check's log
            page.wait_for_selector(".log span", timeout=30000)
            time.sleep(1.5)
            page.keyboard.press("1")                                            # back to Now: run 3 got the slot
            third = page.locator(".run-card", has_text="rounding")
            page.wait_for_selector(".run-card:not(.waiting) >> text=rounding", timeout=40000)
            time.sleep(2.0)
            third.click()
            page.wait_for_selector(".g-node.st-running[data-step='build']", timeout=20000)
            time.sleep(1.0)
            page.click(".g-node[data-step='build']")
            page.wait_for_selector(".g-node.st-failed[data-step='test'], .g-node[data-step='test'] >> text=/2 tries/", timeout=60000)
            page.wait_for_selector(".g-node[data-step='test'] >> text=/fix/", timeout=60000)
            page.click(".g-node[data-step='test']")                             # the failed attempt and its fix
            page.wait_for_selector(".chip[data-source='test.1.log']", timeout=20000)
            page.click(".chip[data-source='test.1.log']")
            page.wait_for_selector(".log span", timeout=10000)
            for proc in runs:
                proc.wait(timeout=120)
            time.sleep(2.0)
            page.keyboard.press("Escape")                                       # the whole run: graph, timeline, outcome
            time.sleep(3.5)
            page.keyboard.press("2")                                            # history with totals
            time.sleep(3.5)
            print(f"recorded {time.monotonic() - started:.1f} s")
            video = Path(page.video.path())
            context.close()
            browser.close()
        convert(video, out)
    finally:
        for proc in runs:
            if proc.poll() is None:
                proc.terminate()
        dashboard.terminate()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "demo" / "dashboard")
    parser.add_argument("--workdir", type=Path)
    parser.add_argument("--setup-only", action="store_true", help="create the app and layer, print the layer path, stop")
    parser.add_argument("--keep", action="store_true", help="keep the work directory")
    args = parser.parse_args()
    work = args.workdir or Path(tempfile.mkdtemp(prefix="al-dash-demo."))
    layer = setup(work)
    print(f"layer: {layer}")
    if args.setup_only:
        return 0
    if not CHROME:
        sys.exit("no Chrome found (set AL_DASHBOARD_CHROME)")
    try:
        record(layer, args.out, work)
    finally:
        if not args.keep and not args.workdir:
            shutil.rmtree(work, ignore_errors=True)   # the runtime already removed each run's container and worktree
    return 0


if __name__ == "__main__":
    sys.exit(main())
