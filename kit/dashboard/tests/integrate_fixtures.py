"""The scenario of "Resolve with an agent", as code: an invented application `pantry/` with real git
history and a layer `pantry.al/` beside it (laid out by start_layer.build_layer, so its own
adws/integrate.py can run an integration with the mock agent).

The application has `stock.py` (a function `total(items)`), `INDEX.md` (generated by `./index.sh`,
which lists the `*.py` files), `tests/test_stock.py` and `deploy/release.cfg` (a protected path).
Its checkout is on the side branch `work`, so `main` is not checked out. The layer's workflow
`ship-it` (plan, check `test`, auto review, ship) merges without a person; its
templates/integrate.json names INDEX.md as generated by ./index.sh; mock/integrate/resolve.json is
what the mock agent does at the resolve step (one `total()` that takes both sides, INDEX.md
regenerated, the report).

  f0000001  handed over: merge conflict in stock.py and INDEX.md (the acceptance run)  → needs you
  f0000002  handed over: adds prices.py only; `ship-failed:` because main moved (applies cleanly)
  f0000003  handed over: its review rejected it                    → needs you, not offered
  f0000004  handed over: merge conflict, and it changes deploy/release.cfg → refused (protected-path)
  f0000005  handed over: merge conflict; its branch has one more commit, by a person → refused
  f0000006  handed over: its work is on main already, by a squash merge  → landed (patch-id)
  f0000007  handed over; c0000002 redid it                                → settled (superseded)
  c0000002  passed and shipped: "Redo f0000007 on the new price table"
  a0000003  passed and shipped: the run that moved main ("Add a tax")

So: needs you 5, landed 1, settled 1, done 2. Git runs with a fixed author, committer and dates.
Every name is invented.
"""
from __future__ import annotations

import json
import subprocess
from datetime import datetime, timedelta, timezone
from pathlib import Path

import settle_fixtures as sf
import start_layer

ADW = "ship-it"
ACCEPTANCE, CLEAN, REJECTED, PROTECTED, CHANGED, LANDED, REPLACED = (f"f000000{n}" for n in range(1, 8))
REPLACEMENT, MOVER = "c0000002", "a0000003"
HANDED_OVER = [ACCEPTANCE, CLEAN, REJECTED, PROTECTED, CHANGED, LANDED, REPLACED]
NEEDS_YOU = [ACCEPTANCE, CLEAN, REJECTED, PROTECTED, CHANGED]

STOCK = "def total(items):\n    return sum(items)\n"
RUN_STOCK = "def total(items, discount=0):\n    return sum(items) - discount\n"
MAIN_STOCK = "def total(items, tax=0):\n    return sum(items) + tax\n"
BOTH_STOCK = "def total(items, discount=0, tax=0):\n    return sum(items) - discount + tax\n"
INDEX_HEADER = "<!-- Generated by ./index.sh; DO NOT EDIT -->"
INDEX_SH = ("#!/bin/sh\n# writes INDEX.md: one line per python file\n"
            "{ echo '" + INDEX_HEADER + "'; echo '# Index'; echo; "
            "for f in *.py; do echo \"- $f\"; done; } > INDEX.md\n")
BOTH_INDEX = INDEX_HEADER + "\n# Index\n\n- shelf.py\n- shop.py\n- stock.py\n"
REPORT = {"resolved": [{"file": "stock.py", "sides": "the run added a discount, main added a tax",
                        "resolution": "one total() that takes both"}],
          "regenerated": [{"file": "INDEX.md", "command": "./index.sh"}], "undecidable": []}
CONFLICT = "merge-conflict:ship: git merge --no-edit main failed: CONFLICT (content): Merge conflict in stock.py"
MOVED = "ship-failed:git push . HEAD:refs/heads/main failed: ! [rejected] HEAD -> main (non-fast-forward)"

RUNS = {
    ACCEPTANCE: ("Give stock a discount", [CONFLICT],
                 {"stock.py": RUN_STOCK, "shelf.py": "SHELF = 1\n", "INDEX.md": None,
                  "tests/test_discount.py": "from stock import total\n\n\ndef test_discount():\n"
                                            "    assert total([5], discount=1) == 4\n"}),
    CLEAN: ("Add a price table", [MOVED], {"prices.py": "PRICES = {}\n"}),
    REJECTED: ("Count the stock twice", ["review-rejected"],
               {"stock.py": "def total(items):\n    return sum(items) + sum(items)\n"}),
    PROTECTED: ("Release to the beta channel", [CONFLICT],
                {"stock.py": "def total(items, channel='beta'):\n    return sum(items)\n",
                 "deploy/release.cfg": "channel = beta\n"}),
    CHANGED: ("Round the total", [CONFLICT], {"stock.py": "def total(items):\n    return round(sum(items))\n"}),
    LANDED: ("Label the shelves", [MOVED], {"labels.py": "LABELS = []\n"}),
    REPLACED: ("List the prices", [MOVED], {"pricelist.py": "PRICELIST = []\n"}),
}


def _write(repo: Path, files: dict) -> None:
    for name, text in files.items():
        if text is None:
            continue
        path = repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        if name.endswith(".sh"):
            path.chmod(0o755)
    if "INDEX.md" in files and files["INDEX.md"] is None:   # regenerated, as its header says
        subprocess.run(["./index.sh"], cwd=repo, check=True, capture_output=True, timeout=30)


def _slug(title: str) -> str:
    return "-".join("".join(c for c in word if c.isalnum()) for word in title.lower().split()[:6])


def branch_of(run_id: str) -> str:
    return f"chore/{run_id}-{_slug(RUNS[run_id][0])}"


def build_repo(repo: Path) -> dict[str, str]:
    """pantry/ with main, one branch per handed-over run, and the checkout on `work` → {name: commit}."""
    repo.mkdir(parents=True)
    git = sf.Git(repo)
    git("init", "-q", "-b", "main")
    _write(repo, {"README.md": "# pantry\n\nKeeps track of what is in the pantry.\n", "stock.py": STOCK,
                  "index.sh": INDEX_SH, "tests/test_stock.py": "from stock import total\n\n\ndef test_total():\n"
                                                               "    assert total([1, 2]) == 3\n",
                  "deploy/release.cfg": "channel = stable\n", "INDEX.md": None})
    git("add", "-A")
    tips = {"base": git.commit("pantry: first commit")}
    for run_id, (title, _reasons, files) in RUNS.items():
        git("checkout", "-q", "-b", branch_of(run_id), "main")
        _write(repo, files)
        git("add", "-A")
        tips[run_id] = git.commit(f"chore: {title} [adw {run_id}]")
        if run_id == CHANGED:      # a person adds a commit to the run's branch afterwards
            _write(repo, {"NOTES.txt": "rounding: half up, as agreed\n"})
            git("add", "-A")
            tips["person"] = git.commit("a note on rounding")
        git("checkout", "-q", "main")
    _write(repo, {"stock.py": MAIN_STOCK, "shop.py": "SHOP = 1\n", "INDEX.md": None,
                  "tests/test_tax.py": "from stock import total\n\n\ndef test_tax():\n    assert total([5], tax=1) == 6\n"})
    git("add", "-A")
    tips[MOVER] = git.commit(f"feature: Add a tax [adw {MOVER}]")
    git("merge", "-q", "--squash", branch_of(LANDED))
    tips["squash"] = git.commit("chore: Label the shelves (squashed)")
    _write(repo, {"price_table.py": "PRICE_TABLE = {}\n"})
    git("add", "-A")
    tips[REPLACEMENT] = git.commit(f"chore: Redo {REPLACED} on the new price table [adw {REPLACEMENT}]")
    tips["main"] = tips[REPLACEMENT]
    git("checkout", "-q", "-b", "work")
    return tips


def _change(data: dict) -> None:
    data["description"] = "the pantry's agentic layer"
    data["codebase"]["root"] = "../pantry"
    data["codebase"]["paths"] = {"protected": ["deploy"], "tests": ["tests"]}


def build_layer(root: Path, repo: Path, *, with_integrate: bool = True) -> Path:
    layer = start_layer.build_layer(root, "pantry", repo, None, port_base=28900, change=_change,
                                    with_integrate=with_integrate)
    (layer / "templates").mkdir(exist_ok=True)
    (layer / "templates" / "integrate.json").write_text(json.dumps(
        {"version": 1, "generated": [{"path": "INDEX.md", "regenerate": "./index.sh"}]}, indent=2) + "\n")
    script = layer / "mock" / "integrate" / "resolve.json"
    script.parent.mkdir(parents=True, exist_ok=True)
    output = "Resolved the conflicts.\n\n```json\n" + json.dumps(REPORT, indent=2) + "\n```\n"
    script.write_text(json.dumps({"raw_files": {"stock.py": BOTH_STOCK, "INDEX.md": BOTH_INDEX}, "output": output}))
    return layer


def _iso(when: datetime) -> str:
    return when.isoformat()


def _steps(start: datetime, end: datetime, rejected: bool = False) -> list[dict]:
    names = [("plan", "run"), ("test", "check"), ("review", "review"), ("ship", "ship")]
    return [{"name": name, "kind": kind, "status": "rejected" if rejected and name == "review" else "passed",
             "attempts": 1, "started": _iso(start), "ended": _iso(end), "detail": ""} for name, kind in names]


def build_scenario(root: Path, *, with_integrate: bool = True) -> dict:
    """root/pantry (the application) and root/pantry.al (the layer) with the nine runs above."""
    root.mkdir(parents=True, exist_ok=True)
    repo = root / "pantry"
    tips = build_repo(repo)
    layer = build_layer(root, repo, with_integrate=with_integrate)
    base = datetime.now(timezone.utc).replace(microsecond=0) - timedelta(days=2)
    for index, (run_id, (title, reasons, _files)) in enumerate(RUNS.items()):
        start = base + timedelta(minutes=10 * index)
        end = start + timedelta(minutes=6)
        rejected = "review-rejected" in reasons
        verdict = {"success": not rejected, "mode": "auto", "summary": "the total is wrong" if rejected else "looks right",
                   "issues": ([{"severity": "blocker", "description": "the stock is counted twice",
                                "resolution": "count it once"}] if rejected else [])}
        plan = layer / "specs" / f"plan-{run_id}.md"
        plan.parent.mkdir(exist_ok=True)
        plan.write_text(f"# Plan: {title}\n\n## Acceptance Criteria\n\n- the tests pass\n")
        sf.write_run(layer, run_id, adw=ADW, prompt=f"{title}\n\nAsked for by the shop.", status="handed-over",
                     dry_run=False, class_fixed=True, started=_iso(start), ended=_iso(end), branch=branch_of(run_id),
                     plan=str(plan), steps=_steps(start, end, rejected),
                     checks={"test": {"exit": 0, "log": f"agents/{run_id}/checks/test.log"}},
                     review={"mode": "auto", "verdict": verdict,
                             "rounds": [{"round": 1, "reviewers": [verdict], "verdict": verdict}]},
                     ship={"action": "pr", "shipped": False, "handed_over": list(reasons), "reasons": list(reasons),
                           "commit": tips[run_id], "target": f"agents/{run_id}/PR.md", "pr": None})
        (layer / "agents" / run_id / "PR.md").write_text(f"# chore: {title}\n")
    for index, (run_id, title, klass) in enumerate(((MOVER, "Add a tax", "feature"),
                                                    (REPLACEMENT, f"Redo {REPLACED} on the new price table", "chore"))):
        start = base + timedelta(hours=3, minutes=20 * index)
        end = start + timedelta(minutes=7)
        sf.write_run(layer, run_id, adw=ADW, prompt=title, status="passed", dry_run=False, klass=klass,
                     started=_iso(start), ended=_iso(end), branch=f"{klass}/{run_id}-{_slug(title)}",
                     steps=_steps(start, end), ship={"action": "merge", "shipped": True, "commit": tips[run_id],
                                                     "target": "main", "reasons": []})
    return {"root": root, "repo": repo, "layer": layer, "tips": tips, "base": base}


def git(repo: Path, *args: str) -> str:
    done = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, timeout=60)
    assert done.returncode == 0, done.stderr
    return done.stdout.strip()


def state_of(layer: Path, run_id: str) -> dict:
    return json.loads((layer / "agents" / run_id / "state.json").read_text())


def record_of(layer: Path, run_id: str, name: str = "integration.json") -> dict:
    return json.loads((layer / "agents" / run_id / name).read_text())


def integration_runs(layer: Path) -> list[str]:
    """Ids of the layer's integration runs, oldest first."""
    found = []
    for path in (layer / "agents").glob("*/state.json"):
        data = json.loads(path.read_text())
        if data.get("adw") == "integrate":
            found.append((str(data.get("started") or ""), str(data["adw_id"])))
    return [run_id for _started, run_id in sorted(found)]


def add_conflicting_run(layer: Path, repo: Path, run_id: str, title: str, files: dict, base: str) -> dict:
    """One more handed-over run with a merge conflict: `files` committed on its own branch cut from
    `base` (through a throwaway worktree, so the application's checkout is not touched)."""
    branch = f"chore/{run_id}-{_slug(title)}"
    tree = repo.parent / f"tree-{run_id}"
    git_ = sf.Git(repo)
    git_("worktree", "add", "-q", "-b", branch, str(tree), base)
    _write(tree, files)
    inside = sf.Git(tree)
    inside("add", "-A")
    commit = inside.commit(f"chore: {title} [adw {run_id}]")
    git_("worktree", "remove", "--force", str(tree))
    start = datetime.now(timezone.utc).replace(microsecond=0) - timedelta(hours=1)
    end = start + timedelta(minutes=5)
    verdict = {"success": True, "mode": "auto", "summary": "looks right", "issues": []}
    sf.write_run(layer, run_id, adw=ADW, prompt=f"{title}\n\nAsked for by the shop.", status="handed-over",
                 dry_run=False, class_fixed=True, started=_iso(start), ended=_iso(end), branch=branch,
                 steps=_steps(start, end), review={"mode": "auto", "verdict": verdict,
                                                   "rounds": [{"round": 1, "reviewers": [verdict], "verdict": verdict}]},
                 ship={"action": "pr", "shipped": False, "handed_over": [CONFLICT], "reasons": [CONFLICT],
                       "commit": commit, "target": f"agents/{run_id}/PR.md", "pr": None})
    return {"id": run_id, "branch": branch, "commit": commit}
