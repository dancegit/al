PROMOTE_SCRIPT = HEADER + '''"""Promotion between the layer's stages: `run FROM TO`, `decide FROM TO …`, `status FROM TO`
(what `al promote` and `al decide` call). See adw_modules/promotion.py.
Generated by `al gen` because agentic.rkt declares stages — edit agentic.rkt, not this file.
"""
import sys
from pathlib import Path

adws_dir = Path(__file__).resolve().parent
sys.path.insert(0, str(adws_dir))
from adw_modules import promotion  # noqa: E402

if __name__ == "__main__":
    sys.exit(promotion.main(Path(__file__).resolve().parent.parent, sys.argv[1:]))
'''


def git(repo: Path, *args: str) -> str:
    done = subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", *args],
                          capture_output=True, text=True, timeout=60)
    assert done.returncode == 0, done.stderr
    return done.stdout.strip()


