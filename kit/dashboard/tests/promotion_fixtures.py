def build_promotion_site(root: Path, *, open_promotion: bool = True) -> dict:
    """root/app (VERSION, CHANGELOG.md, the sprint 2026-s47; the checkout on a branch of its own) and
    root/shop.al with three delivered changes and, unless told otherwise, the promotion waiting."""
    app = root / "app"
    app.mkdir(parents=True)
    git(app, "init", "-q", "-b", "main")
    (app / "app.py").write_text("print('shop')\n")
    (app / "test.sh").write_text("#!/bin/sh\nexit 0\n")
    (app / "test.sh").chmod(0o755)
    (app / "VERSION").write_text("0.1.0\n")
    (app / "CHANGELOG.md").write_text("# Changelog\n\n## [Unreleased]\n\n## [0.1.0] - 2026-01-02\n\n- first\n")
    git(app, "add", "-A")
    git(app, "commit", "-qm", "release 0.1.0")
    head = git(app, "rev-parse", "HEAD")
    git(app, "branch", SPRINT, "main")
    git(app, "checkout", "-q", "-b", "work")
    layer = root / "shop.al"
    data = _ir(app)
    (layer / "commands").mkdir(parents=True)
    for command in data["commands"]:
        (layer / "commands" / f"{command['name']}.md").write_text(f"# {command['name']}\n\n$ARGUMENTS\n")
    (layer / "agentic-layer.json").write_text(json.dumps(data, indent=1))
    adws = layer / "adws"
    shutil.copytree(RUNTIME / "adw_modules", adws / "adw_modules", ignore=shutil.ignore_patterns("__pycache__"))
    for adw in data["adws"]:
        (adws / f"adw_{adw['name']}.py").write_text(adw_script(adw))
    (adws / "promote.py").write_text(PROMOTE_SCRIPT)
    (adws / "dispatch.py").write_text(HEADER + (RUNTIME / "dispatch.py").read_text())
    (layer / "agents").mkdir()
    (layer / "agents" / "cycle.json").write_text(json.dumps({
        "version": 1, "kind": "sprint", "stage": "sprint", "history": [],
        "current": {"name": "2026-s47", "version": "", "opened_at": "2026-11-16T09:30:00+00:00", "n": 1,
                    "branch": SPRINT, "from_commit": head}}, indent=2))
    for adw_id, name, prompt, criteria in CHANGES:
        deliver(layer, adw_id, name, prompt, criteria)
    shot = _attach(layer, "tiny.png", "artefacts/0000c001/screenshots/cart.png")
    _record(layer, "0000c001", {"id": "screenshots", "type": "image", "step": "test",
                                "path": "artefacts/0000c001/screenshots/cart.png", "bytes": shot.stat().st_size})
    video = _attach(layer, "tiny.webm", "artefacts/0000c002/recording/search.webm")
    frame = _attach(layer, "tiny.png", "artefacts/0000c002/recording/search.keyframes/frame-001.png")
    _record(layer, "0000c002", {"id": "recording", "type": "video", "step": "test",
                                "path": "artefacts/0000c002/recording/search.webm", "bytes": video.stat().st_size,
                                "keyframes": [{"path": "artefacts/0000c002/recording/search.keyframes/frame-001.png",
                                               "bytes": frame.stat().st_size}]})
    site = {"root": root, "app": app, "layer": layer, "changes": [c[0] for c in CHANGES], "run": ""}
    if open_promotion:
        done = script(layer, "promote.py", "run", "sprint", "main")
        assert done.returncode == 75, done.stdout + done.stderr
        site["run"] = json.loads((layer / "agents" / "promotions" / "sprint-main.json").read_text())["id"]
    return site


def _attach(layer: Path, data_file: str, rel: str) -> Path:
    """A copy of tests/data/<data_file> at <layer>/<rel>, as `artefacts.collect` leaves one."""
    target = layer / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(DATA / data_file, target)
    return target


def _record(layer: Path, adw_id: str, artefact: dict) -> None:
    """Appends an artefact record to agents/<adw_id>/state.json."""
    state_path = layer / "agents" / adw_id / "state.json"
    state = json.loads(state_path.read_text())
    state["artefacts"].append(artefact)
    state_path.write_text(json.dumps(state, indent=2))


def script(layer: Path, name: str, *argv: str) -> subprocess.CompletedProcess:
    env = {k: v for k, v in __import__("os").environ.items() if k != "AL_APP_ROOT"}
    return subprocess.run([sys.executable, str(layer / "adws" / name), *argv], cwd=layer, capture_output=True,
                          text=True, timeout=300, env=env)


def deliver(layer: Path, adw_id: str, name: str, prompt: str, criteria: list[str] | None) -> None:
    mock = layer / "mock" / "demo"
    mock.mkdir(parents=True, exist_ok=True)
    plan = f"specs/plan-{adw_id}.md"
    text = f"# Plan: {prompt}\n\nAdds {name}.\n\n"
    if criteria:
        text += "## Acceptance Criteria\n\n" + "".join(f"- {c}\n" for c in criteria)
    (mock / "plan.json").write_text(json.dumps({"layer_files": {plan: text}, "output": plan}))
    (mock / "build.json").write_text(json.dumps({"files": {name: f"{name.split('.')[0].upper()} = 1\n"}}))
    done = script(layer, "adw_demo.py", prompt, "--class", "feature", "--adw-id", adw_id)
    assert done.returncode == 0, done.stdout + done.stderr
