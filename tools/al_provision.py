"""Provisioning files of a (host …) declaration: pure renderers and the facts they share.

From one host record of the IR, `al gen` writes three committed files under the layer:

    env/hosts/<id>/home-manager.nix   a Home Manager module (options: enable, checkout, layerDir, envFile, dashboardPort)
    env/hosts/<id>/nixos.nix          a NixOS module (options: enable, user)
    env/hosts/<id>/provision.sh       a POSIX shell script for Debian/Ubuntu, Fedora and Arch (--check, --yes)

None of them names a host, a user, an address or a secret: host paths are module options (set by the
host-local wrapper `al deploy` writes under ~/.config/al/<name>/ on the host), the script only uses
$HOME. The three are rendered from the same facts (wanted()), and `al deploy --status` compares the
host with those facts too.

Package versions and checksums come from one data file, kit/host/pins.json (test seam, not in the
usage text: AL_HOST_PINS names another file).

Standard library only.
"""
from __future__ import annotations

import json
import os
import re
import shlex
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
PINS = ROOT / "kit" / "host" / "pins.json"
GENERATED = "# Generated by al from agentic.rkt — do not edit."
SUBID_RANGE = "100000-165535"

# The POSIX programs provision.sh calls, besides shell builtins and the package-manager commands of
# FAMILIES (tests/tools/deploy_host.py links these into a fake host's bin/).
SCRIPT_TOOLS = ("sh", "id", "uname", "grep", "sed", "cut", "head", "mkdir", "mktemp", "rm", "cp", "mv", "chmod",
                "tar", "sha256sum", "curl", "sudo", "getsubids", "loginctl", "usermod", "cat", "test")

# family -> how to install, how to ask whether a package is installed, and the package names.
FAMILIES: dict[str, dict[str, Any]] = {
    "debian": {"detect": "apt-get", "install": "apt-get install -y --no-install-recommends",
               "query": "dpkg-query -W -f='${Status}\\n' {pkg} 2>/dev/null | grep -q 'install ok installed'",
               "commands": ("apt-get", "dpkg-query"),
               "packages": {"podman": ["podman", "uidmap", "slirp4netns"], "git": ["git"], "curl": ["curl"],
                            "ca-certificates": ["ca-certificates"]}},
    "fedora": {"detect": "dnf", "install": "dnf install -y",
               "query": "rpm -q {pkg} >/dev/null 2>&1",
               "commands": ("dnf", "rpm"),
               "packages": {"podman": ["podman", "shadow-utils", "slirp4netns"], "git": ["git"], "curl": ["curl"],
                            "ca-certificates": ["ca-certificates"]}},
    "arch": {"detect": "pacman", "install": "pacman -S --noconfirm --needed",
             "query": "pacman -Q {pkg} >/dev/null 2>&1",
             "commands": ("pacman",),
             "packages": {"podman": ["podman", "shadow", "slirp4netns"], "git": ["git"], "curl": ["curl"],
                          "ca-certificates": ["ca-certificates"]}},
}

# agent kind -> pins key; the CLI name is al_deploy.AGENT_LOGIN's
AGENT_PIN = {"claude-code": "claude", "codex": "codex"}
NIX_AGENT = {"claude-code": "claude-code", "codex": "codex"}
NIX_BASE_PACKAGES = ("git", "uv")                       # what the Nix modules install besides podman and the agent CLIs
DISTRO_BASE_PACKAGES = ("git", "curl", "ca-certificates")  # what provision.sh installs with the package manager
PINNED_BASE = ("uv",)                                    # pinned downloads besides the agent CLIs (kit/host/pins.json)


def _deploy() -> Any:
    if "al_deploy" in sys.modules:
        return sys.modules["al_deploy"]
    if str(ROOT / "tools") not in sys.path:
        sys.path.insert(0, str(ROOT / "tools"))
    import al_deploy
    return al_deploy


def load_pins() -> dict:
    path = Path(os.environ.get("AL_HOST_PINS") or PINS)
    return json.loads(path.read_text())


def needs_podman(ir: dict) -> bool:
    return (any(e.get("kind") == "podman" for e in ir.get("environments") or [])
            or (ir.get("dashboard") or {}).get("kind") == "podman")


def declared_units(ir: dict) -> list[str]:
    kinds = [k for k in ("cron", "webhook") if any(t.get("kind") == k for t in ir.get("triggers") or [])]
    if (ir.get("dashboard") or {"kind": "local"}).get("kind") != "none":
        kinds.append("dashboard")
    return kinds


def host_units(ir: dict, decl: dict | None) -> list[str]:
    """The units a host keeps running: the declaration's #:units, or every unit the layer declares."""
    declared = declared_units(ir)
    if decl and decl.get("units"):
        return [u for u in declared if u in decl["units"]]
    return declared


def dashboard_port(ir: dict, decl: dict | None) -> int:
    if decl and decl.get("dashboardPort"):
        return int(decl["dashboardPort"])
    return int((ir.get("dashboard") or {}).get("port") or 8765)


def with_host_port(ir: dict, decl: dict | None) -> dict:
    """The IR with the dashboard's port replaced by the host's #:dashboard-port, when it sets one."""
    dashboard = ir.get("dashboard")
    if not decl or not decl.get("dashboardPort") or not isinstance(dashboard, dict):
        return ir
    return {**ir, "dashboard": {**dashboard, "port": int(decl["dashboardPort"])}}


def agent_kinds(ir: dict) -> list[str]:
    seen: list[str] = []
    for agent in _deploy().used_agents(ir):
        if agent.get("kind") in AGENT_PIN and agent["kind"] not in seen:
            seen.append(agent["kind"])
    return seen


def wanted(ir: dict, decl: dict | None) -> list[dict[str, str]]:
    """The facts every provisioning style establishes, and drift compares: one dict per fact with
    `fact` and `want` (plain words)."""
    pins = load_pins()
    facts = [{"fact": "git", "want": "installed"}, {"fact": "uv", "want": pins["uv"]["version"]}]
    if needs_podman(ir):
        facts += [{"fact": "podman rootless", "want": "yes"}, {"fact": "subids", "want": f"ranges for the user"}]
    for kind in agent_kinds(ir):
        key = AGENT_PIN[kind]
        facts.append({"fact": key, "want": pins[key]["version"]})
    if not decl or decl.get("linger", True):
        facts.append({"fact": "linger", "want": "yes"})
    facts.append({"fact": "units", "want": " ".join(host_units(ir, decl)) or "none"})
    return facts


