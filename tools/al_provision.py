def nixos_module(ir: dict, decl: dict) -> str:
    name = ir["name"]
    podman = "\n    virtualisation.podman.enable = true;" if needs_podman(ir) else ""
    linger = "true" if decl.get("linger", True) else "false"
    return f'''{GENERATED}
# NixOS module for a machine of kind `{decl["id"]}` that runs the {name} agentic layer: what a user
# cannot set for themselves (podman, subuid/subgid ranges, lingering). It holds no host name and no
# user: `al deploy --as {decl["id"]} --provision` writes a host-local ~/.config/al/{name}/nixos.nix
# that imports this file and sets `user`; import that file from your NixOS configuration.
{{ config, lib, pkgs, ... }}:
let
  cfg = config.services."al-{name}-host";
in {{
  options.services."al-{name}-host" = {{
    enable = lib.mkEnableOption "what the {name} agentic layer needs from the system";
    user = lib.mkOption {{
      type = lib.types.str;
      description = "The user that runs the layer.";
    }};
  }};

  config = lib.mkIf cfg.enable {{{podman}
    users.users.${{cfg.user}}.autoSubUidGidRange = true;
    users.users.${{cfg.user}}.linger = {linger};
    environment.systemPackages = with pkgs; [ git uv ];
  }};
}}
'''


