def _nix_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${") + '"'


def home_manager_module(ir: dict, name: str, module: str, packages: list[str], *, layer_default: str = "",
                        units: list[tuple[str, dict[str, str]]] | None = None, host: dict | None = None) -> str:
    """Without `host`: the text of env/home-manager.nix of an (environment home-manager …), unchanged.
    With `host` (a host record): env/hosts/<id>/home-manager.nix, whose host values are options and
    whose units are rendered from `units` ((kind, al.unit_spec(kind, …)) pairs)."""
    if host is None:
        cron = next((t for t in ir["triggers"] if t["kind"] == "cron"), None)
        service = f'''
    systemd.user.services."al-{name}-cron" = {{
      Unit.Description = "Agentic layer cron trigger for {name}";
      Service.ExecStart = "${{pkgs.uv}}/bin/uv run ${{cfg.layerDir}}/adws/triggers/trigger_cron.py";
      Service.Restart = "on-failure";
      Install.WantedBy = [ "default.target" ];
    }};''' if cron else ""
        return f'''{GENERATED}
# Import from your Home Manager configuration:
#   imports = [ {layer_default}/env/home-manager.nix ];
#   programs.{module}.enable = true;
{{ config, lib, pkgs, ... }}:
let
  cfg = config.programs."{module}";
  adw = pkgs.writeShellScriptBin "al-{name}" \'\'
    # al-{name} <adw> [args…]   run an ADW of the {name} agentic layer
    if [ $# -lt 1 ]; then ls "${{cfg.layerDir}}/adws" | sed -n 's/^adw_\\(.*\\)\\.py$/\\1/p'; exit 0; fi
    exec ${{pkgs.uv}}/bin/uv run "${{cfg.layerDir}}/adws/adw_$1.py" "''${{@:2}}"
  \'\';
in {{
  options.programs."{module}" = {{
    enable = lib.mkEnableOption "the agentic layer for {name}";
    layerDir = lib.mkOption {{
      type = lib.types.str;
      default = "{layer_default}";
      description = "Directory of the generated agentic layer.";
    }};
  }};

  config = lib.mkIf cfg.enable {{
    home.packages = (with pkgs; [ {' '.join(packages)} uv git ]) ++ [ adw ];
    home.sessionVariables.AL_{re.sub(r'[^A-Z0-9]', '_', name.upper())}_LAYER = cfg.layerDir;{service}
  }};
}}
'''
    layer_dir = (ir.get("layer") or {}).get("dir") or "agentic"
    dashboard = ir.get("dashboard") or {"kind": "local", "port": 8765}
    agents = [NIX_AGENT[k] for k in agent_kinds(ir)]
    pkgs = [*NIX_BASE_PACKAGES, *(["podman"] if needs_podman(ir) else []), *agents]
    unfree = ("\n    # claude-code is unfree: allow it, e.g. nixpkgs.config.allowUnfreePredicate = p: "
              "builtins.elem (lib.getName p) [ \"claude-code\" ];" if "claude-code" in agents else "")
    services = []
    for kind, spec in units or []:
        args = ""
        if kind == "dashboard":
            args = (" --bind 127.0.0.1" if dashboard.get("kind") == "local" else "") + " --port ${toString cfg.dashboardPort}"
        lines = [f'    systemd.user.services."al-{name}-{kind}" = {{',
                 # a committed file names no URL: the dashboard's loopback address without its scheme
                 f"      Unit.Description = {_nix_str(spec['description'].replace('http://', ''))};",
                 f'      Service.ExecStart = "${{pkgs.uv}}/bin/uv run ${{cfg.layerDir}}/{spec["script"]}{args}";',
                 '      Service.Environment = "PATH=${config.home.profileDirectory}/bin:/run/wrappers/bin:/usr/bin:/bin";',
                 '      Service.EnvironmentFile = "-${cfg.envFile}";']
        if spec["env_file"]:
            lines.append(f'      # the dashboard\'s access token: {spec["env_file"].splitlines()[0].lstrip("# ")}')
        lines.append(f'      Service.Restart = "{spec["restart"]}";')
        if spec["restart_sec"]:
            lines.append(f"      Service.RestartSec = {spec['restart_sec']};")
        lines += ['      Install.WantedBy = [ "default.target" ];', "    };"]
        services.append("\n".join(lines))
    port = dashboard_port(ir, host)
    return f'''{GENERATED}
# Home Manager module for a machine of kind `{host["id"]}` that runs the {name} agentic layer.
# It holds no host name, user or path: `al deploy --as {host["id"]} --provision` writes a host-local
# ~/.config/al/{name}/home.nix that imports this file and sets `checkout`; import that file from
# your Home Manager configuration.
#
# Prerequisites it cannot set for a user: subuid/subgid ranges, newuidmap/newgidmap and lingering.
# nixos.nix of this directory sets them on NixOS, provision.sh on Debian/Ubuntu, Fedora and Arch;
# lingering alone: sudo loginctl enable-linger "$USER".
{{ config, lib, pkgs, ... }}:
let
  cfg = config.services."al-{name}";
in {{
  options.services."al-{name}" = {{
    enable = lib.mkEnableOption "the {name} agentic layer on this machine";
    checkout = lib.mkOption {{
      type = lib.types.str;
      description = "The repository checkout al deploy keeps up to date on this machine.";
    }};
    layerDir = lib.mkOption {{
      type = lib.types.str;
      default = "${{cfg.checkout}}/{layer_dir}";
      description = "Directory of the agentic layer inside the checkout.";
    }};
    envFile = lib.mkOption {{
      type = lib.types.str;
      default = "%h/.config/al/{name}.env";
      description = "KEY=VALUE file with the layer's secrets (names in agentic.rkt, values only on this machine).";
    }};
    dashboardPort = lib.mkOption {{
      type = lib.types.port;
      default = {port};
      description = "Port of the dashboard on 127.0.0.1.";
    }};
  }};

  config = lib.mkIf cfg.enable {{{unfree}
    home.packages = with pkgs; [ {' '.join(pkgs)} ];
{chr(10).join(services)}
  }};
}}
'''


