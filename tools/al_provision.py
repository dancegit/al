def _downloads(ir: dict, pins: dict) -> list[tuple[str, dict]]:
    keys = [*PINNED_BASE, *[AGENT_PIN[k] for k in agent_kinds(ir)]]
    return [(key, pins[key]) for key in keys]


def provision_script(ir: dict, decl: dict, pins: dict) -> str:
    name, ident = ir["name"], decl["id"]
    podman = needs_podman(ir)
    linger = bool(decl.get("linger", True))
    wanted_pkgs = [*DISTRO_BASE_PACKAGES, *(["podman"] if podman else [])]
    family_cases = []
    for family, f in FAMILIES.items():
        pkgs = " ".join(p for key in wanted_pkgs for p in f["packages"][key])
        query = f["query"].replace("{pkg}", '"$1"')
        family_cases.append(f'''  if command -v {f["detect"]} >/dev/null 2>&1; then
    family={family}; packages="{pkgs}"; install="{f["install"]}"
    installed() {{ {query}; }}
    return 0
  fi''')
    tools = []
    for key, pin in _downloads(ir, pins):
        assets = pin["assets"]
        tools.append(f'''  {key})
    bin={shlex.quote(pin.get("bin") or key)}; version={shlex.quote(pin["version"])}
    case "$arch" in
      x86_64) url={shlex.quote(assets["x86_64"]["url"])}; sum={assets["x86_64"]["sha256"]}; member={shlex.quote(assets["x86_64"].get("member", ""))};;
      aarch64) url={shlex.quote(assets["aarch64"]["url"])}; sum={assets["aarch64"]["sha256"]}; member={shlex.quote(assets["aarch64"].get("member", ""))};;
      *) echo "unsupported architecture: $arch" >&2; exit 2;;
    esac;;''')
    tool_keys = " ".join(key for key, _ in _downloads(ir, pins))
    return f'''#!/bin/sh
{GENERATED}
# Provisions a machine of kind `{ident}` to run the {name} agentic layer: the distribution packages
# (git, curl{", podman and its rootless helpers" if podman else ""}), subuid/subgid ranges{", lingering" if linger else ""} and, without
# privilege, uv and the agent CLI at pinned versions in ~/.local/bin (sha256 checked).
# It names no host, user or secret. Debian/Ubuntu, Fedora and Arch.
#
#   sh provision.sh --check   print the plan and change nothing
#   sh provision.sh           print the plan, ask, then apply it
#   sh provision.sh --yes     print the plan and apply it without asking
#
# Every privileged command is printed in the plan (privileged: …) and again just before it runs
# (+ …); it runs through sudo -n, so it never waits for a password. When privilege is refused the
# script stops with exit 3 and prints the commands for a person to run.
set -eu

mode=ask
case "${{1:-}}" in
  --check) mode=check;;
  --yes) mode=yes;;
  "") ;;
  -h|--help) sed -n '2,15p' "$0" 2>/dev/null || true; exit 0;;
  *) echo "unknown argument: $1 (use --check, --yes or --help)" >&2; exit 2;;
esac

user=$(id -un)
if [ "$(id -u)" = 0 ]; then SUDO=""; else SUDO="sudo -n "; fi
bindir="$HOME/.local/bin"
arch=$(uname -m)
case "$arch" in arm64) arch=aarch64;; amd64) arch=x86_64;; esac

detect() {{
{chr(10).join(family_cases)}
  return 1
}}

pin() {{
  case "$1" in
{chr(10).join(tools)}
  esac
}}

has_version() {{
  # $1: program, $2: version; true when the program on PATH or in ~/.local/bin reports it
  for p in "$bindir/$1" "$(command -v "$1" 2>/dev/null || true)"; do
    if [ -n "$p" ] && [ -x "$p" ] && "$p" --version 2>/dev/null | head -n 1 | grep -qF "$2"; then return 0; fi
  done
  return 1
}}

privileged=""
todo=0
missing_pkgs=""
missing_tools=""

note_priv() {{
  echo "    privileged: $SUDO$*"
  privileged="$privileged
$*"
}}

echo "provisioning plan for {name} (host {ident}):"
if detect; then
  for p in $packages; do
    if ! installed "$p"; then missing_pkgs="$missing_pkgs $p"; fi
  done
  missing_pkgs=${{missing_pkgs# }}
  if [ -n "$missing_pkgs" ]; then
    echo "  packages ($family): missing $missing_pkgs"
    note_priv "$install $missing_pkgs"
    todo=$((todo + 1))
  else
    echo "  packages ($family): ok"
  fi
else
  family=""
  echo "  packages: no apt-get, dnf or pacman found; install by hand: git curl{" podman and its rootless helpers (newuidmap, slirp4netns)" if podman else ""}"
fi
{f"""if getsubids "$user" >/dev/null 2>&1 || grep -q "^$user:" /etc/subuid 2>/dev/null; then
  echo "  subids: ok"
  subids=ok
else
  echo "  subids: missing for $user (rootless podman needs subuid/subgid ranges)"
  note_priv usermod --add-subuids {SUBID_RANGE} --add-subgids {SUBID_RANGE} "$user"
  subids=missing
  todo=$((todo + 1))
fi""" if podman else "subids=ok"}
for t in {tool_keys}; do
  pin "$t"
  if has_version "$bin" "$version"; then
    echo "  $bin $version: ok"
  else
    echo "  $bin $version: missing; installs into ~/.local/bin (sha256 checked)"
    missing_tools="$missing_tools $t"
    todo=$((todo + 1))
  fi
done
{'''if [ "$(loginctl show-user "$user" --property=Linger 2>/dev/null | sed 's/^Linger=//')" = yes ]; then
  echo "  linger: ok"
  linger=ok
else
  echo "  linger: off (the units would stop when $user logs out)"
  note_priv loginctl enable-linger "$user"
  linger=missing
  todo=$((todo + 1))
fi''' if linger else "linger=ok"}

if [ "$todo" -eq 0 ]; then
  echo "provisioning: nothing to do"
  exit 0
fi
if [ "$mode" = check ]; then
  echo "provisioning: $todo item(s) to do; nothing was changed (--check)"
  exit 0
fi
if [ "$mode" = ask ]; then
  if [ ! -t 0 ]; then echo "provisioning needs --yes when no terminal can answer" >&2; exit 4; fi
  printf 'apply this plan? [y/N] '
  read -r answer
  case "$answer" in y|Y|yes) ;; *) echo "nothing was changed"; exit 1;; esac
fi

download() {{
  pin "$1"
  tmp=$(mktemp -d)
  if ! curl -fsSL -o "$tmp/download" "$url"; then rm -rf "$tmp"; echo "download failed: $bin $version" >&2; exit 1; fi
  got=$(sha256sum "$tmp/download" | cut -d ' ' -f 1)
  if [ "$got" != "$sum" ]; then
    rm -rf "$tmp"
    echo "checksum mismatch for $bin $version: expected $sum, got $got; nothing was installed" >&2
    exit 1
  fi
  if [ -n "$member" ]; then
    mkdir -p "$tmp/x"
    tar -xzf "$tmp/download" -C "$tmp/x" "$member"
    file="$tmp/x/$member"
  else
    file="$tmp/download"
  fi
  mkdir -p "$bindir"
  cp "$file" "$bindir/.$bin.new"
  chmod 755 "$bindir/.$bin.new"
  mv "$bindir/.$bin.new" "$bindir/$bin"
  rm -rf "$tmp"
  echo "installed $bin $version into ~/.local/bin"
}}

refused() {{
  echo "privilege was refused (exit $1) for: $SUDO$2" >&2
  echo "nothing more was changed; run these as a privileged user on this machine, then provision again:"
  printf '%s\\n' "$privileged" | sed -n 's/^\\(..*\\)$/  sudo \\1/p'
  exit 3
}}

priv() {{
  # the words of a privileged command (package names, a user name) hold no space and no pattern
  cmd=$*
  echo "+ $SUDO$cmd"
  set -f
  if [ -n "$SUDO" ]; then sudo -n $cmd || refused $? "$cmd"; else $cmd || refused $? "$cmd"; fi
  set +f
}}

downloaded=no
if command -v curl >/dev/null 2>&1; then
  for t in $missing_tools; do download "$t"; done
  downloaded=yes
fi
if [ -n "$missing_pkgs" ]; then
  # shellcheck disable=SC2086
  priv $install $missing_pkgs
fi
if [ "$downloaded" = no ]; then
  for t in $missing_tools; do download "$t"; done
fi
if [ "$subids" = missing ]; then priv usermod --add-subuids {SUBID_RANGE} --add-subgids {SUBID_RANGE} "$user"; fi
if [ "$linger" = missing ]; then priv loginctl enable-linger "$user"; fi
echo "provisioning: done"
'''
