"""A throwaway local Forgejo for the testbed story of the demo video: `make.py forgejo up|down --work DIR`.

  up      starts codeberg.org/forgejo/forgejo:11 in rootless podman, published on the loopback interface
          only, creates an admin `demo` and an empty public repository `demo/flask`, and writes
          DIR/forgejo.json (where it is) and DIR/forgejo.env (its access value, mode 0600)
  down    removes the container with its anonymous data volume, and both files
  status  what `up` wrote for DIR, or None
  reachable  does the instance answer?

The recipe is the one of tests/forge/forgejo_live.sh. The instance, its admin and its access value are
throwaway: the password is random and never stored or printed, the access value is generated by the
instance, is never printed, and both die with the container. The URL is http://localhost:PORT, never an
IPv4 address: the demo video shows it, and its privacy rules allow no address on screen.

Standard library only. `run`, `which` and `http` can be given, so the tests need neither podman nor an
instance.
"""
from __future__ import annotations

import json
import os
import secrets
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

IMAGE = "codeberg.org/forgejo/forgejo:11"
CONTAINER = "al-demo-forgejo"
DEFAULT_PORT = 3910
OWNER = "demo"
REPO = "flask"
TOKEN_VAR = "AL_DEMO_FORGEJO_TOKEN"
STATE = "forgejo.json"
SECRET = "forgejo.env"
START_SECONDS = 60


def base_url(port: int) -> str:
    return f"http://localhost:{port}"


def _http(method: str, url: str, headers: dict | None = None, body: bytes | None = None, timeout: float = 5.0) -> tuple[int, bytes]:
    """One request that never goes through a proxy; (0, b"") when nothing answers."""
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    request = urllib.request.Request(url, data=body, method=method, headers=dict(headers or {}))
    try:
        with opener.open(request, timeout=timeout) as response:
            return response.status, response.read()
    except urllib.error.HTTPError as error:
        return error.code, error.read()
    except (OSError, ValueError):
        return 0, b""


def reachable(url: str, http=None) -> bool:
    """GET {url}/api/v1/version answers 200 within 5 s."""
    status, _data = (http or _http)("GET", url.rstrip("/") + "/api/v1/version", {}, None)
    return status == 200


def status(work: Path) -> dict | None:
    """{"url", "owner", "repo", "token"} of the instance `up` recorded in `work`, or None."""
    try:
        state = json.loads((Path(work) / STATE).read_text(encoding="utf-8"))
        lines = (Path(work) / SECRET).read_text(encoding="utf-8").splitlines()
    except (OSError, ValueError):
        return None
    value = next((line.split("=", 1)[1].strip() for line in lines if line.startswith(TOKEN_VAR + "=")), "")
    if not isinstance(state, dict) or not state.get("url") or not value:
        return None
    return {"url": str(state["url"]), "owner": str(state.get("owner") or OWNER), "repo": str(state.get("repo") or REPO),
            "token": value}


def _podman(run, *args: str, timeout: float = 600):
    return run(["podman", *args], capture_output=True, text=True, timeout=timeout)


def down(work: Path, run=subprocess.run, which=shutil.which) -> int:
    """Remove the container with its anonymous data volume, and the two files of `work`. 0 even when
    nothing was running."""
    if which("podman"):
        _podman(run, "rm", "-f", "-v", CONTAINER)
    for name in (STATE, SECRET):
        (Path(work) / name).unlink(missing_ok=True)
    print("removed the Forgejo container and its data", flush=True)
    return 0


def up(work: Path, port: int = DEFAULT_PORT, run=subprocess.run, which=shutil.which, http=None) -> int:
    """Start the instance and write DIR/forgejo.json and DIR/forgejo.env. 0 when it is up, 2 without
    podman, 1 (with everything removed again) when a step fails."""
    if which("podman") is None:
        print("make.py forgejo: podman is not on PATH; the Forgejo instance runs in rootless podman", file=sys.stderr)
        return 2
    http = http or _http
    work = Path(work)
    url = base_url(port)
    _podman(run, "rm", "-f", "-v", CONTAINER)
    if _podman(run, "image", "exists", IMAGE).returncode != 0:
        pulled = _podman(run, "pull", "-q", IMAGE, timeout=1800)
        if pulled.returncode != 0:
            print(f"make.py forgejo: cannot pull {IMAGE}: {(pulled.stderr or '').strip()[-300:]}", file=sys.stderr)
            return 1
    settings = ["FORGEJO__security__INSTALL_LOCK=true", "FORGEJO__database__DB_TYPE=sqlite3",
                f"FORGEJO__server__ROOT_URL={url}/", "FORGEJO__server__OFFLINE_MODE=true",
                "FORGEJO__picture__DISABLE_GRAVATAR=true", "FORGEJO__service__DISABLE_REGISTRATION=true",
                "FORGEJO__log__LEVEL=Warn"]
    argv = ["run", "-d", "--name", CONTAINER, "-p", f"127.0.0.1:{port}:3000"]
    for setting in settings:
        argv += ["-e", setting]
    started = _podman(run, *argv, IMAGE)
    if started.returncode != 0:
        print(f"make.py forgejo: the container did not start: {(started.stderr or '').strip()[-300:]}", file=sys.stderr)
        down(work, run=run, which=which)
        return 1

    def stop(reason: str) -> int:
        print(f"make.py forgejo: {reason}", file=sys.stderr)
        down(work, run=run, which=which)
        return 1

    deadline = time.monotonic() + START_SECONDS
    while not reachable(url, http):
        if time.monotonic() >= deadline:
            return stop(f"the instance did not answer on {url} within {START_SECONDS} s")
        time.sleep(1)
    # a throwaway admin of a container that `down` deletes: the password is random, used once, never kept
    password = secrets.token_urlsafe(18) + "A1!"
    created = _podman(run, "exec", "-u", "git", CONTAINER, "forgejo", "admin", "user", "create", "--username", OWNER,
                      "--password", password, "--email", f"{OWNER}@example.org", "--admin", "--must-change-password=false")
    if created.returncode != 0:
        return stop("the admin user could not be created: "
                    + (created.stderr or "").replace(password, "…").strip()[-300:])
    generated = _podman(run, "exec", "-u", "git", CONTAINER, "forgejo", "admin", "user", "generate-access-token",
                        "--username", OWNER, "--token-name", "al-demo", "--scopes", "all", "--raw")
    lines = [line.strip() for line in (generated.stdout or "").splitlines() if line.strip()]
    if generated.returncode != 0 or not lines:
        return stop("the instance gave no access value for its admin")
    value = lines[-1]
    body = json.dumps({"name": REPO, "default_branch": "main", "private": False, "auto_init": False}).encode("utf-8")
    code, _data = http("POST", f"{url}/api/v1/user/repos",
                       {"Authorization": f"token {value}", "Content-Type": "application/json", "Accept": "application/json"}, body)
    if code not in (200, 201):
        return stop(f"the repository {OWNER}/{REPO} could not be created (HTTP {code})")
    work.mkdir(parents=True, exist_ok=True)
    (work / STATE).write_text(json.dumps({"url": url, "port": port, "owner": OWNER, "repo": REPO, "container": CONTAINER,
                                          "image": IMAGE}, indent=2) + "\n", encoding="utf-8")
    secret = work / SECRET
    secret.unlink(missing_ok=True)
    handle = os.open(secret, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(handle, "w", encoding="utf-8") as out:
        out.write(f"{TOKEN_VAR}={value}\n")
    os.chmod(secret, 0o600)
    print(f"Forgejo: {url}/{OWNER}/{REPO} (an empty repository; remove it with make.py forgejo down --work {work})", flush=True)
    return 0
